static inline int32_t MontgomerymapFull(int64_t a)  
{
    uint32_t m = (uint32_t)a * (uint32_t)INVERSE_Q;
    int64_t t = (int64_t)m * BIT_Q;

    int32_t r = (int32_t)((a - t) >> 32);
    r = r + ((r >> 31) & BIT_Q);
    return r;
}
static inline int32_t mul_mod(int32_t a, int32_t b)
{
     return MontgomerymapFull((int64_t)a*(int64_t)b);
}

static int NTT_Lazy (int32_t *a) {
    int t, m, i, j, s, e;
    int64_t U = 0, V = 0;
    int32_t S;
    t = BIT_N;

    for (m = 1; m < BIT_N / 2; m <<= 1) {
        t = (t >> 1);
        for (i = 0; i < m; ++i) {
            s = (i * t) << 1;
            e = s + t;
            S = M[m + i];
            for (j = s; j < e; ++j) {
                U = a[j];
                V = a[j + t];
                V = mul_mod(V, S);
                a[j] = reduce_modq(U + V);
                a[j + t] = reduce_modq(U - V + BIT_Q);
            }
        }
    }
    return 0;
}

static int INTT_Lazy (int32_t *a) {
    int t, m, i, j, s, e;
    int64_t U = 0, V = 0;
    int32_t S;
    t = 2;

    for (m = BIT_N / 2; m > 1; m >>= 1) {
        s = 0;
        int h = m >> 1;
        for (i = 0; i < h; ++i) {
            e = s + t;
            S = Mn[h + i];
            for (j = s; j < e; ++j) {
                U = a[j];
                V = a[j + t];
                a[j] = reduce_modq(U + V);
                a[j + t] = mul_mod(reduce_modq(U - V + BIT_Q), S);
            }
            s += 2 * t;
        }
        t <<= 1;
    }

    for (i = 0; i < BIT_N; ++i) {
        a[i] = mul_mod(a[i], INVERSE_N_BETA);
    }
    return 0;
}

void ntt_forward(int32_t a[BIT_N]) {
    (void)NTT_Lazy(a);
}

void ntt_inverse(int32_t a[BIT_N]) {
    (void)INTT_Lazy(a);
}

void ntt_basemul_raw(int32_t r[BIT_N], const int32_t a[BIT_N], const int32_t b[BIT_N]) {
    int j = 0;

    for (int i = 0; i < BIT_N - 3; i += 4) {
        int32_t root = M[(BIT_N/4)+j];
        int32_t tmp;

        tmp = mul_mod(a[i], b[i]) + mul_mod(mul_mod(a[i+1], b[i+1]), root);
        r[i] = reduce_modq(tmp);

        tmp = mul_mod(a[i] , b[i+1]) + mul_mod(a[i+1] , b[i]);
        r[i+1] = reduce_modq(tmp);

        tmp = mul_mod(a[i+2] , b[i+2]) + mul_mod( mul_mod(a[i+3] , b[i+3]) , (BIT_Q-root) );
        r[i+2] = reduce_modq(tmp);

        tmp = mul_mod(a[i+2] , b[i+3]) + mul_mod(a[i+3], b[i+2]);
        r[i+3] = reduce_modq(tmp);

        j++;
    }
}

void ntt_basemul_acc_raw(int32_t r[BIT_N], const int32_t a[BIT_N], const int32_t b[BIT_N]) {
    int j = 0;

    for (int i = 0; i < BIT_N - 3; i += 4) {
        int32_t root = M[(BIT_N/4)+j];
        int32_t tmp;
        int32_t val;

        tmp = mul_mod(a[i], b[i]) + mul_mod(mul_mod(a[i+1], b[i+1]), root);
        val = r[i] + reduce_modq(tmp) - BIT_Q;
        val += (val >> 31) & BIT_Q;
        r[i] = (int32_t)val;

        tmp = mul_mod(a[i] , b[i+1]) + mul_mod(a[i+1] , b[i]);
        val = r[i+1] + reduce_modq(tmp) - BIT_Q;
        val += (val >> 31) & BIT_Q;
        r[i+1] = (int32_t)val;

        tmp = mul_mod(a[i+2] , b[i+2]) + mul_mod( mul_mod(a[i+3] , b[i+3]) , (BIT_Q-root) );
        val = r[i+2] + reduce_modq(tmp) - BIT_Q;
        val += (val >> 31) & BIT_Q;
        r[i+2] = (int32_t)val;

        tmp = mul_mod(a[i+2] , b[i+3]) + mul_mod(a[i+3], b[i+2]);
        val = r[i+3] + reduce_modq(tmp) - BIT_Q;
        val += (val >> 31) & BIT_Q;
        r[i+3] = (int32_t)val;

        j++;
    }
}

void ntt_montgomery_lift(int32_t r[BIT_N]) {
    for (int i = 0; i < BIT_N; i++) {
        r[i] = mul_mod(r[i], MONT_R2);
    }
}
