/*
 * Fully vectorized rejection sampling using ML-KEM's pshufb technique.
 * Processes 32 candidates (from 48 bytes) per main loop iteration.
 *
 * 1. Load 24 bytes, shuffle to extract 16 x 12-bit values
 * 2. Compare against Q
 * 3. Pack comparison mask, lookup shuffle indices
 * 4. pshufb to compact accepted values
 * 5. Store compacted values, advance output pointer by popcount
 */
unsigned int rej_uniform(int16_t *res,
                         unsigned int len,
                         const unsigned char *buf,
                         unsigned int buflen) {
    unsigned int ctr, pos;
    uint16_t val0, val1;
    uint32_t good;
    const __m256i bound = _mm256_set1_epi16((int16_t)DKE_Q);
    const __m256i ones  = _mm256_set1_epi8(1);
    const __m256i mask  = _mm256_set1_epi16(0xFFF);
    /* low 128 extracts candidates from buf bytes 0..11; after permute4x64(0x94)
     * the high 128 holds buf bytes 8..23, so it must index bytes 4..15 to pull
     * candidates 8..15 (bytes 12..23). The two lanes therefore DIFFER (matches
     * ML-KEM's idx8). The earlier broadcast-to-both-lanes form was the bug that
     * corrupted candidates 8..15. */
    const __m256i idx8  = _mm256_setr_epi8(
         0, 1, 1, 2, 3, 4, 4, 5, 6, 7, 7, 8, 9,10,10,11,
         4, 5, 5, 6, 7, 8, 8, 9,10,11,11,12,13,14,14,15);
    __m256i f0, f1, g0, g1, g2, g3;
    __m128i f, t, pilo, pihi;

    ctr = pos = 0;

    /* Main loop: process 32 candidates from 48 bytes */
    while (ctr <= len - 32 && pos + 48 <= buflen) {
        f0 = _mm256_loadu_si256((__m256i *)&buf[pos]);
        f1 = _mm256_loadu_si256((__m256i *)&buf[pos + 24]);
        f0 = _mm256_permute4x64_epi64(f0, 0x94);
        f1 = _mm256_permute4x64_epi64(f1, 0x94);
        f0 = _mm256_shuffle_epi8(f0, idx8);
        f1 = _mm256_shuffle_epi8(f1, idx8);
        g0 = _mm256_srli_epi16(f0, 4);
        g1 = _mm256_srli_epi16(f1, 4);
        f0 = _mm256_blend_epi16(f0, g0, 0xAA);
        f1 = _mm256_blend_epi16(f1, g1, 0xAA);
        f0 = _mm256_and_si256(f0, mask);
        f1 = _mm256_and_si256(f1, mask);
        pos += 48;

        /* Compare: -1 where val < Q */
        g0 = _mm256_cmpgt_epi16(bound, f0);
        g1 = _mm256_cmpgt_epi16(bound, f1);

        /* Pack 16-bit comparison results to 8-bit, get 32-bit mask */
        g0 = _mm256_packs_epi16(g0, g1);
        good = (uint32_t)_mm256_movemask_epi8(g0);

        /* Lookup shuffle indices for each 8-value group */
        g0 = _mm256_castsi128_si256(_mm_loadl_epi64((__m128i *)&rej_idx[(good >>  0) & 0xFF]));
        g1 = _mm256_castsi128_si256(_mm_loadl_epi64((__m128i *)&rej_idx[(good >>  8) & 0xFF]));
        g0 = _mm256_inserti128_si256(g0, _mm_loadl_epi64((__m128i *)&rej_idx[(good >> 16) & 0xFF]), 1);
        g1 = _mm256_inserti128_si256(g1, _mm_loadl_epi64((__m128i *)&rej_idx[(good >> 24) & 0xFF]), 1);

        /* Expand byte indices to 16-bit pair indices */
        g2 = _mm256_add_epi8(g0, ones);
        g3 = _mm256_add_epi8(g1, ones);
        g0 = _mm256_unpacklo_epi8(g0, g2);
        g1 = _mm256_unpacklo_epi8(g1, g3);

        /* Compact accepted values via pshufb */
        f0 = _mm256_shuffle_epi8(f0, g0);
        f1 = _mm256_shuffle_epi8(f1, g1);

        /* Store and advance by popcount of each 8-bit group */
        _mm_storeu_si128((__m128i *)&res[ctr], _mm256_castsi256_si128(f0));
        ctr += _mm_popcnt_u32((good >>  0) & 0xFF);
        _mm_storeu_si128((__m128i *)&res[ctr], _mm256_extracti128_si256(f0, 1));
        ctr += _mm_popcnt_u32((good >> 16) & 0xFF);
        _mm_storeu_si128((__m128i *)&res[ctr], _mm256_castsi256_si128(f1));
        ctr += _mm_popcnt_u32((good >>  8) & 0xFF);
        _mm_storeu_si128((__m128i *)&res[ctr], _mm256_extracti128_si256(f1, 1));
        ctr += _mm_popcnt_u32((good >> 24) & 0xFF);
    }

    /* Medium loop: process 8 candidates from 12 bytes (SSE) */
    while (ctr <= len - 8 && pos + 12 <= buflen) {
        f = _mm_loadu_si128((__m128i *)&buf[pos]);
        f = _mm_shuffle_epi8(f, _mm256_castsi256_si128(idx8));
        t = _mm_srli_epi16(f, 4);
        f = _mm_blend_epi16(f, t, 0xAA);
        f = _mm_and_si128(f, _mm256_castsi256_si128(mask));
        pos += 12;

        t = _mm_cmpgt_epi16(_mm256_castsi256_si128(bound), f);
        good = (uint32_t)_mm_movemask_epi8(t);
        /* Extract one bit per 16-bit lane (portable, no BMI2 needed) */
        good &= 0x5555;
        good = (good | (good >> 1)) & 0x3333;
        good = (good | (good >> 2)) & 0x0F0F;
        good = (good | (good >> 4)) & 0x00FF;

        pilo = _mm_loadl_epi64((__m128i *)&rej_idx[good]);
        pihi = _mm_add_epi8(pilo, _mm256_castsi256_si128(ones));
        pilo = _mm_unpacklo_epi8(pilo, pihi);
        f = _mm_shuffle_epi8(f, pilo);
        _mm_storeu_si128((__m128i *)&res[ctr], f);
        ctr += _mm_popcnt_u32(good);
    }

    /* Scalar tail */
    while (ctr < len && pos + 3 <= buflen) {
        val0 = ((buf[pos+0] >> 0) | ((uint16_t)buf[pos+1] << 8)) & 0xFFF;
        val1 = ((buf[pos+1] >> 4) | ((uint16_t)buf[pos+2] << 4));
        pos += 3;
        if (val0 < DKE_Q)
            res[ctr++] = (int16_t)val0;
        if (val1 < DKE_Q && ctr < len)
            res[ctr++] = (int16_t)val1;
    }

    return ctr;
}

