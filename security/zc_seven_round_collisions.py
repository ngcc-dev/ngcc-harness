CAND = {"DM": (30, "ZC-DM"), "DMC": (31, "ZC-DMC")}
SHIM = '#include "ZuD1536-plain.h"\nvoid zc_permute7(ZuD1536_plain64_state *s) { ZuD1536_plain_Permute_Nrounds(s, 7); }\n'


def build(tmp, mode, n, rounds):
    cid, name = CAND[mode]
    impl = ROOT / f"hash-{cid}/{name}/Implementations"
    ref = impl / f"Implementations/Reference_Implementation/{name}-1536-{n}"
    plain = impl / "lib/low/ZuD-1536/plain"
    inc = ["-I", str(ref), "-I", str(impl / "lib/common"), "-I", str(plain)]
    objs = []
    for src, defs in ((ref / "CryptHash_AlgorithmInstance.c",
                       ["-DZuD1536_plain_Permute_12rounds=zc_permute7"] if rounds == 7 else []),
                      (plain / "ZuD1536-plain.c", []), (tmp / "shim.c", [])):
        obj = tmp / f"{name}-{n}-{rounds}-{src.stem}.o"
        subprocess.run(["cc", "-O2", "-fPIC", "-c"] + inc + defs + ["-o", str(obj), str(src)],
                       check=True, stdout=subprocess.DEVNULL)
        objs.append(str(obj))
    so = tmp / f"{name}-{n}-{rounds}.so"
    subprocess.run(["cc", "-shared", "-o", str(so)] + objs, check=True, stdout=subprocess.DEVNULL)
    return ctypes.CDLL(str(so))


def digest(lib, n, msg):
    out = ctypes.create_string_buffer(n // 8)
    if lib.CryptHash(n, msg, ctypes.c_ulonglong(8 * len(msg)), out) != 0:
        raise RuntimeError("CryptHash failed")
    return out.raw


def main():
    if shutil.which("cc") is None or not all(
            (ROOT / f"hash-{cid}/{name}/Implementations/lib").is_dir() for cid, name in CAND.values()):
        print("SKIP: C compiler or extracted ZC-DM/ZC-DMC sources unavailable")
        return 77
    ok = True
    with tempfile.TemporaryDirectory(prefix="ngcc-zc7-") as t:
        tmp = Path(t)
        (tmp / "shim.c").write_text(SHIM)
        for mode, n, bits, m0, m1, posted in PAIRS:
            m0, m1, posted = bytes.fromhex(m0), bytes.fromhex(m1), bytes.fromhex(posted)
            lib7, lib12 = build(tmp, mode, n, 7), build(tmp, mode, n, 12)
            c7 = [digest(lib7, n, m) for m in (m0, m1)]
            c12 = [digest(lib12, n, m) for m in (m0, m1)]
            model7 = [zc_hash(mode, 1536, n, m, rounds=7) for m in (m0, m1)]
            model12 = [zc_hash(mode, 1536, n, m) for m in (m0, m1)]
            checks = {
                "distinct messages of the posted length": m0 != m1 and 8 * len(m0) == 8 * len(m1) == bits,
                "seven-round digests equal": c7[0] == c7[1],
                "equal to the posted digest": c7[0] == posted,
                "independent model agrees": model7 == c7,
                "twelve-round digests differ": c12[0] != c12[1] and c12 == model12,
            }
            rate = (1536 - n - 64) // 8
            blocks = sorted({i // rate for i in range(len(m0)) if m0[i] != m1[i]})
            print(f"{CAND[mode][1]}-1536-{n}: " + "; ".join(f"{k}: {'yes' if v else 'NO'}" for k, v in checks.items())
                  + f"; differing bytes in rate blocks {blocks}")
            ok &= all(checks.values())
    if not ok:
        print("NOT VERIFIED hash-30-2/hash-31-3 follow-up: a posted seven-round collision did not reproduce")
        return 1
    print("LEAD hash-30-2/hash-31-3 FOLLOW-UP VERIFIED: posted seven-round collisions for ZC-DM and ZC-DMC "
          "1536-512 and 1536-768 reproduce on the submitted code; no twelve-round collision")
    return 0


if __name__ == "__main__":
    sys.exit(main())
