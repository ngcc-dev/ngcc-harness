void compute_zeta_mul_inv_avx2(int16_t zetas_mul_inv_avx2[N])
{
    for (int i = 0; i < 1536 / 12; ++i)
    {
        zetas_mul_inv_avx2[3 * i] = zetas[128 + 2 * i];
        zetas_mul_inv_avx2[3 * i + 1] = zetas_base[i];
        zetas_mul_inv_avx2[3 * i + 2] = (-zetas[128 + 2 * i] - zetas_base[i] + 3457) % 3457;
    }
}

