void ntt(int16_t *a)
{
  unsigned int len, start, j, k = 1;
  int16_t t, z[3], zeta, zeta1, rho = zetas_ref[0];

  zeta = zetas_ref[k++];
  for (j = 0; j < DTRU_N / 2; ++j)
  {
    t = fqmul(zeta, a[j + DTRU_N / 2]);
    a[j + DTRU_N / 2] = barrett_reduce(a[j] + a[j + DTRU_N / 2] - t);
    a[j] = barrett_reduce(a[j] + t);
  }

  for (len = DTRU_N / 4; len >= 96; len >>= 1)
  {
    for (start = 0; start < DTRU_N; start = j + len)
    {
      zeta = zetas_ref[k++];
      for (j = start; j < start + len; ++j)
      {
        t = fqmul(zeta, a[j + len]);
        a[j + len] = (a[j] - t);
        a[j] = (a[j] + t);
      }
    }
  }

  len = 48;
  for (start = 0; start < DTRU_N; start = j + len)
  {
    zeta = zetas_ref[k++];
    for (j = start; j < start + len; ++j)
    {
      t = fqmul(zeta, a[j + len]);
      a[j + len] = barrett_reduce(a[j] - t);
      a[j] = barrett_reduce(a[j] + t);
    }
  }

  for (len = 24; len >= 12; len >>= 1)
  {
    for (start = 0; start < DTRU_N; start = j + len)
    {
      zeta = zetas_ref[k++];
      for (j = start; j < start + len; ++j)
      {
        t = fqmul(zeta, a[j + len]);
        a[j + len] = (a[j] - t);
        a[j] = (a[j] + t);
      }
    }
  }

  len = 6;
  for (start = 0; start < DTRU_N; start = j + len)
  {
    zeta = zetas_ref[k++];
    for (j = start; j < start + len; ++j)
    {
      t = fqmul(zeta, a[j + len]);
      a[j + len] = barrett_reduce(a[j] - t);
      a[j] = barrett_reduce(a[j] + t);
    }
  }

  for (start = 0; start < DTRU_N; start =  j + 2 * ROOT_DIMENSION)
  {
    zeta = zetas_ref[k++];
    zeta1 = zetas_ref[k++];
    for (j = start; j < start + ROOT_DIMENSION; ++j)
    {
      z[0] = fqmul(zeta, a[j + ROOT_DIMENSION]);
      z[1] = fqmul(zeta1, a[j + 2 * ROOT_DIMENSION]);
      z[2] = fqmul(rho, z[0] - z[1]);
      a[j + ROOT_DIMENSION] = barrett_reduce(a[j] + z[2] - z[1]);
      a[j + 2 * ROOT_DIMENSION] = barrett_reduce(a[j] - z[2] - z[0]);
      a[j] = barrett_reduce(a[j] + z[0] + z[1]);
    }
  }
}

void invntt(int16_t *a)
{
  unsigned int start, len, j, k = 0;
  int16_t t, z[3], zeta, zeta1, rho = zetas_inv_ref[383];

  for (start = 0; start < DTRU_N; start = j + 2 * ROOT_DIMENSION)
  {
    zeta = zetas_inv_ref[k++];
    zeta1 = zetas_inv_ref[k++];
    for (j = start; j < start + ROOT_DIMENSION; ++j)
    {
      z[0] = a[j + ROOT_DIMENSION];
      z[1] = a[j + 2 * ROOT_DIMENSION];
      z[2] = fqmul(rho, z[0] - z[1]);
      a[j + ROOT_DIMENSION] = fqmul(zeta, a[j] + z[2] - z[1]);
      a[j + 2 * ROOT_DIMENSION] = fqmul(zeta1, a[j] - z[2] - z[0]);
      a[j] = barrett_reduce(a[j] + z[0] + z[1]);
    }
  }

  for (len = 3 * ROOT_DIMENSION; len <= 12; len <<= 1)
  {
    for (start = 0; start < DTRU_N; start = j + len)
    {
      zeta = zetas_inv_ref[k++];
      for (j = start; j < start + len; ++j)
      {
        t = a[j];
        a[j] = (t + a[j + len]);
        a[j + len] = (t - a[j + len]);
        a[j + len] = fqmul(zeta, a[j + len]);
      }
    }
  }

  len = 24;
  for (start = 0; start < DTRU_N; start = j + len)
  {
    zeta = zetas_inv_ref[k++];
    for (j = start; j < start + len; ++j)
    {
      t = a[j];
      a[j] = barrett_reduce(t + a[j + len]);
      a[j + len] = fqmul(zeta, t - a[j + len]);
    }
  }

  for (len = 48; len <= 96; len <<= 1)
  {
    for (start = 0; start < DTRU_N; start = j + len)
    {
      zeta = zetas_inv_ref[k++];
      for (j = start; j < start + len; ++j)
      {
        t = a[j];
        a[j] = (t + a[j + len]);
        a[j + len] = (t - a[j + len]);
        a[j + len] = fqmul(zeta, a[j + len]);
      }
    }
  }

  len = 192;
  for (start = 0; start < DTRU_N; start = j + len)
  {
    zeta = zetas_inv_ref[k++];
    for (j = start; j < start + len; ++j)
    {
      t = a[j];
      a[j] = barrett_reduce(t + a[j + len]);
      a[j + len] = fqmul(zeta, t - a[j + len]);
    }
  }

  zeta = zetas_inv_ref[k++];
  for (j = 0; j < DTRU_N / 2; ++j)
  {
    t = fqmul(zeta, a[j] - a[j + DTRU_N / 2]);
    a[j] = fqmul(zetas_inv_ref[384], a[j] + a[j + DTRU_N / 2] - t);
    a[j + DTRU_N / 2] = fqmul(zetas_inv_ref[385], t);
  }
}

#define CALC_D(a, b, x, y, d) (fqmul((a[x] + a[y]), (b[x] + b[y])) - d[x] - d[y])

void basemul(int16_t *c, const int16_t *a, const int16_t *b, const int16_t zeta)
{
  int16_t d[2];
  for (int i = 0; i < 2; i++)
    d[i] = fqmul(a[i], b[i]);

  c[0] = barrett_reduce(d[0] + fqmul(zeta, d[1]));
  c[1] = barrett_reduce(CALC_D(a, b, 0, 1, d));
}
