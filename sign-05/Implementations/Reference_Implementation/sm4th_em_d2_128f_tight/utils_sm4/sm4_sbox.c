/*
 * Pull in the field library and bit utilities.
 *   bf8_inv_sm4  — multiplicative inverse in GF(2^8) w/ SM4 modulus
 *   parity8      — XOR of all 8 bits of a byte
 *   set_bit      — place bit b at position pos in a byte
 */
#include "fields.h"
#include "utils.h"

/*
 * SM4 affine transform:  y = A·x + c  (over GF(2))
 *
 * Equation: S(x) = A·inverse(A·x + c) + c
 * A ∈ F_2^{8×8},  c ∈ F_2^8
 *
 * The bit-level implementation computes row-wise:
 * Output bit i is computed as the inner product of A's row i with x.
 *
 *   y[i] = <A[i], x>  ⊕  c[i]
 *        = parity8(x & row_mask[i])  ^  c[i]
 *
 * where row_mask[i] encodes ROW i of A.
 * parity8(v) computes v[0]⊕v[1]⊕…⊕v[7], realizing the GF(2) inner product.
 *
 * Row mask encoding: bit j of row_mask[i] == A[i][j]  (bit 0 = LSB).
 * Row masks derived from the SM4 specification (GB/T 32907-2016):
 *
 *   Output  Row i of A (LSB-first display)  row_mask[i]
 *   bit i   A[i][0] ... A[i][7]             (hex)
 *   ------  ------------------------------  -----------
 *     0     1 1 1 0 0 1 0 1                  0xA7
 *     1     1 1 1 1 0 0 1 0                  0x4F
 *     2     0 1 1 1 1 0 0 1                  0x9E
 *     3     1 0 1 1 1 1 0 0                  0x3D
 *     4     0 1 0 1 1 1 1 0                  0x7A
 *     5     0 0 1 0 1 1 1 1                  0xF4
 *     6     1 0 0 1 0 1 1 1                  0xE9
 *     7     1 1 0 0 1 0 1 1                  0xD3
 *
 * Constant c = (c[0]..c[7]) = (1,1,0,0,1,0,1,1).
 * Packed as a byte with c[j] at bit j, this is 0xD3 (LSB-first bit order).
 *
 * Bit-order note:
 *   - When we print a row as "11010011", that is MSB-first display.
 *   - When we store the same row as row_mask[i] = 0xD3, bit 0 is the LSB.
 *
 * Note the MSB-first or LSB-first display
 *
 *  Example for x = 0x01 = 10000000 (LSB-first bit order)
 *   A·x + c = 11010011 (LSB-first) + 11001011 = 00011000 (LSB-first) = 0x18
 *   inv(0x18) = 0xEF = 11110111 (LSB-first)
 *   A·11110111 + c = 11000010 + 11001011 = 00001001 (LSB-first) = 0x90
 *  
 * NOTE: the reason why we use LSB x  is that we implement bf8_inv_sm4 in LSB-first bit order, so the input and output of the S-box are in LSB-first bit order.
 */
static uint8_t sm4_affine(uint8_t x)
{
    return sm4_affine_byte(x);
}

/*
 * Algebraic SM4 S-box:  S(x) = affine( bf8_inv_sm4( affine(x) ) )
 *
 * According to GB/T 32907-2016, the S-box combines:
 * 1. Affine transformation in GF(2): y = A·x + c
 * 2. Multiplicative inverse in GF(2^8) with irreducible polynomial
 *    f(t) = t^8 + t^7 + t^6 + t^5 + t^4 + t^2 + 1 (hex: 0xF5)
 * 3. Another affine transformation (same A and c as step 1)
 *
 * bf8_inv_sm4() is provided by fields.c.
 * bf8_inv_sm4(0) == 0 by convention (matches the S-box table).
 */
uint8_t sm4_compute_sbox(uint8_t in)
{
    return sm4_affine(bf8_inv_sm4(sm4_affine(in)));
}

