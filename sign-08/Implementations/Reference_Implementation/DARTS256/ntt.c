    t4 = fqmul(t4, a);     //1111111

    t3 = fqmul(t4, t4);    //11111110
    t3 = fqmul(t3, t3);    //111111100
    t3 = fqmul(t3, t2);    //111111111

    t4 = fqmul(t4, t4);    //11111110
    t4 = fqmul(t4, t4);    //111111100
    t4 = fqmul(t4, t4);    //1111111000
    t4 = fqmul(t4, t4);    //11111110000
    t4 = fqmul(t4, t4);    //111111100000
