from sympy import isprime

# 满足特定条件的素数查找脚本

# 满足NTT条件的素数 q 需要满足 (q-1) 可被 n 或 n/2 整除
# 找出所有满足 (q-1) 可被 n 或 n/2 整除的素数 q，且 q < limit


def find_primes(n, limit):
    primes = []
    for q in range(2, limit):
        if isprime(q):
            if (q-1) % n == 0 or (q-1) % (n//2) == 0:
                primes.append(q)
    return primes

n = 1024
limit = 140000

result = find_primes(n, limit)
print(result)
print(f"总共找到 {len(result)} 个素数")

