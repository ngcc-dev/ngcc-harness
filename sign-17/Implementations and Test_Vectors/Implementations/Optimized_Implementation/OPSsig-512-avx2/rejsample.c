static inline __m256i rej_eta_process_8(__m128i g0, uint32_t good)
{
  __m128i g1 = _mm_loadl_epi64((const __m128i *)&idxlut[good]);
  __m256i f1, f2;

  g1 = _mm_shuffle_epi8(g0, g1);
  f1 = _mm256_cvtepi8_epi32(g1);
#if ETA == 2
  {
    const __m256i c2 = _mm256_set1_epi32(-2);
    const __m256i c7 = _mm256_set1_epi32(-7);
    const __m256i p5 = _mm256_set1_epi32(5);
    __m256i f3;

    f2 = _mm256_and_si256(_mm256_cmpgt_epi32(c2, f1), p5);
    f3 = _mm256_and_si256(_mm256_cmpgt_epi32(c7, f1), p5);
    f1 = _mm256_add_epi32(f1, f2);
    f1 = _mm256_add_epi32(f1, f3);
  }
#elif ETA == 3
  {
    const __m256i c3 = _mm256_set1_epi32(-3);
    const __m256i p7 = _mm256_set1_epi32(7);

    f2 = _mm256_and_si256(_mm256_cmpgt_epi32(c3, f1), p7);
    f1 = _mm256_add_epi32(f1, f2);
  }
#endif

  return f1;
}

unsigned int rej_uniform_avx(int32_t * restrict r,
                             const uint8_t buf[REJ_UNIFORM_BUFLEN + 8])
{
  unsigned int ctr = 0;
  unsigned int pos = 0;
  uint32_t good;
  __m256i d, tmp;
  const __m256i mask = _mm256_set1_epi32((1U << 26) - 1U);
  const __m256i bound = _mm256_set1_epi32(Q);

  while(pos <= REJ_UNIFORM_BUFLEN - 32) {
    d = _mm256_loadu_si256((const __m256i *)&buf[pos]);
    d = _mm256_and_si256(d, mask);
    pos += 32;

    tmp = _mm256_sub_epi32(d, bound);
    good = (uint32_t)_mm256_movemask_ps(_mm256_castsi256_ps(tmp));
    tmp = _mm256_cvtepu8_epi32(_mm_loadl_epi64((const __m128i *)&idxlut[good]));
    d = _mm256_permutevar8x32_epi32(d, tmp);
    _mm256_storeu_si256((__m256i *)&r[ctr], d);
    ctr += (unsigned int)_mm_popcnt_u32(good);

    if(ctr > N - 8)
      break;
  }

  while(ctr < N && pos + 4 <= REJ_UNIFORM_BUFLEN) {
    uint32_t t = (uint32_t)buf[pos++];
    t |= (uint32_t)buf[pos++] << 8;
    t |= (uint32_t)buf[pos++] << 16;
    t |= (uint32_t)buf[pos++] << 24;
    t &= ((1U << 26) - 1U);

    if(t < Q)
      r[ctr++] = (int32_t)t;
  }

  return ctr;
}

unsigned int rej_eta_avx(int32_t * restrict r,
                         const uint8_t buf[REJ_UNIFORM_ETA_BUFLEN])
{
  unsigned int ctr = 0;
  unsigned int pos = 0;
  uint32_t good;
  __m256i f0, f1;
  __m128i g0;
  const __m256i mask = _mm256_set1_epi8(0x0F);
  const __m256i eta = _mm256_set1_epi8(ETA);
#if ETA == 2
  const __m256i bound = _mm256_set1_epi8(15);
#elif ETA == 3
  const __m256i bound = _mm256_set1_epi8(14);
#endif

  while(ctr <= N - 8 && pos <= REJ_UNIFORM_ETA_BUFLEN - 16) {
    f0 = _mm256_cvtepu8_epi16(_mm_loadu_si128((const __m128i *)&buf[pos]));
    f1 = _mm256_slli_epi16(f0, 4);
    f0 = _mm256_or_si256(f0, f1);
    f0 = _mm256_and_si256(f0, mask);

    f1 = _mm256_sub_epi8(f0, bound);
    f0 = _mm256_sub_epi8(eta, f0);
    good = (uint32_t)_mm256_movemask_epi8(f1);

    g0 = _mm256_castsi256_si128(f0);
    f1 = rej_eta_process_8(g0, good & 0xFFU);
    _mm256_storeu_si256((__m256i *)&r[ctr], f1);
    ctr += (unsigned int)_mm_popcnt_u32(good & 0xFFU);
    good >>= 8;
    pos += 4;

    if(ctr > N - 8) break;
    g0 = _mm_bsrli_si128(g0, 8);
    f1 = rej_eta_process_8(g0, good & 0xFFU);
    _mm256_storeu_si256((__m256i *)&r[ctr], f1);
    ctr += (unsigned int)_mm_popcnt_u32(good & 0xFFU);
    good >>= 8;
    pos += 4;

    if(ctr > N - 8) break;
    g0 = _mm256_extracti128_si256(f0, 1);
    f1 = rej_eta_process_8(g0, good & 0xFFU);
    _mm256_storeu_si256((__m256i *)&r[ctr], f1);
    ctr += (unsigned int)_mm_popcnt_u32(good & 0xFFU);
    good >>= 8;
    pos += 4;

    if(ctr > N - 8) break;
    g0 = _mm_bsrli_si128(g0, 8);
    f1 = rej_eta_process_8(g0, good);
    _mm256_storeu_si256((__m256i *)&r[ctr], f1);
    ctr += (unsigned int)_mm_popcnt_u32(good);
    pos += 4;
  }

  while(ctr < N && pos < REJ_UNIFORM_ETA_BUFLEN) {
    uint32_t t0 = buf[pos] & 0x0F;
    uint32_t t1 = buf[pos++] >> 4;

#if ETA == 2
    if(t0 < 15) {
      t0 = t0 - (205 * t0 >> 10) * 5;
      r[ctr++] = 2 - (int32_t)t0;
    }
    if(t1 < 15 && ctr < N) {
      t1 = t1 - (205 * t1 >> 10) * 5;
      r[ctr++] = 2 - (int32_t)t1;
    }
#elif ETA == 3
    if(t0 < 14) {
      t0 = t0 - (147 * t0 >> 10) * 7;
      r[ctr++] = 3 - (int32_t)t0;
    }
    if(t1 < 14 && ctr < N) {
      t1 = t1 - (147 * t1 >> 10) * 7;
      r[ctr++] = 3 - (int32_t)t1;
    }
#endif
  }

  return ctr;
}
