/* shuttle_rans_encode: encode the merged (q0 ++ qs ++ h) symbol stream
 * into `out` (capacity `cap`), writing backward then memmove-to-front.
 * Returns 0 and sets *out_len on success; -2 on an out-of-support symbol
 * or a capacity/pos underflow (Sign treats -2 as sigEncode = bottom and
 * restarts).  The three symbol arrays are int32 quotients/hint values in
 * logical order; nq0 = n, nqs = n*lenS, nh = n*lenE. */
int shuttle_rans_encode(uint8_t *out, size_t *out_len, size_t cap,
                        const int32_t *q0, const int32_t *qs,
                        const int32_t *h, size_t nq0, size_t nqs,
                        size_t nh);

/* shuttle_rans_decode: STRICT canonical decode of `in` (length in_len)
 * back into the three symbol arrays.  Returns 0 on success; -1 on ANY
 * non-canonical condition (initial-state range, truncation, trailing
 * bytes, non-terminal end state).  The hint range-check, padding-zero
 * check and byte-for-byte re-encode check live in the pack_sig/unpack_sig
 * wrapper (packing.c), which owns the outer container.  Outputs are NOT
 * cleared on failure here; the wrapper clears them. */
int shuttle_rans_decode(int32_t *q0, int32_t *qs, int32_t *h, size_t nq0,
                        size_t nqs, size_t nh, const uint8_t *in,
                        size_t in_len);

