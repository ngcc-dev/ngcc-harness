/* Per-set rANS low-bit split widths + overflow reserve (tools/SigSize.py).
 * RANS_RESERVED_BYTES sized for a 2^-35 per-stream overflow over the TRUE
 * emission PMFs (Phi^{-1}(1-2^-35)~6.86); RANS_B0/RANS_BS are the
 * size-sweep optimum.  Symbol costs come from the quantized rANS tables.
 *   SHUTTLE-128: b0=2 bs=6 R=509 (mu_b=459, sigma_b=5.5); est sig=1183B
 * (target 1005, +178) SHUTTLE-256: b0=2 bs=7 R=879 (mu_b=819,
 * sigma_b=6.9); est sig=2417B (target 2155, +262) SHUTTLE-512: b0=2 bs=7
 * R=1927 (mu_b=1845, sigma_b=10.1); est sig=5001B (target 4552, +449)
 */
#if SHUTTLE_MODE == 128
#    define RANS_B0 2
#    define RANS_BS 6
#    define RANS_RESERVED_BYTES 509
#endif
#if SHUTTLE_MODE == 256
#    define RANS_B0 2
#    define RANS_BS 7
#    define RANS_RESERVED_BYTES 879
#endif
#if SHUTTLE_MODE == 512
#    define RANS_B0 2
#    define RANS_BS 7
#    define RANS_RESERVED_BYTES 1927
#endif
/* @@AUTOGEN:rans_meta@@ END */

/* 2-byte rlen field + zero-padded reserved com region (packet layout).
 */
#define RANS_BLOCK_BYTES (2 + RANS_RESERVED_BYTES)

/* ---- physical signature layout sizes ---------------------------------
 */
/* The raw low-bit body R: per-block ceil because b0 != bs (differs from a
 * single-width body).  z0 block = 1 poly of b0-bit lows; z_s block
 * = ELL polys of b_s-bit lows.  All bit-packed LSB-first (PolyToBytes
 * convention).
 */
#define RANS_Z0_LO_PACKEDBYTES ((N * RANS_B0 + 7) / 8)
#define RANS_ZS_LO_PACKEDBYTES ((ELL * N * RANS_BS + 7) / 8)
#define POLYZ_LO_PACKEDBYTES \
    (RANS_Z0_LO_PACKEDBYTES + RANS_ZS_LO_PACKEDBYTES)

/* SIG_PACKED_BYTES: the fixed length of the compact signature =
 *   seedC (CHALLENGESEEDBYTES) + rlen(2) + reserved com
 * (RANS_RESERVED_BYTES)
 *   + raw low-bit body (POLYZ_LO_PACKEDBYTES).
 * The com region is fixed-size (zero-padded), so pack_sig output is
 * EXACTLY this length.  This is the value sig_get_sn_len_bytes()
 * returns; the params.h CRYPTO_BYTES literal mirrors it exactly (packing.c
 * static-asserts SIG_PACKED_BYTES == CRYPTO_BYTES). */
#define SIG_PACKED_BYTES \
    (CHALLENGESEEDBYTES + RANS_BLOCK_BYTES + POLYZ_LO_PACKEDBYTES)

/* RAW (un-rANS'd) signature length, for the validation packers:
 *   seedC + z1 (Z1LEN polys, 2 bytes/coeff) + hint (EM polys, d_h bits).
 * The hint uses DH_BITS so its range-checked decode recovers [0,H_h). */
#define SIG_RAW_Z1_PACKEDBYTES (2u * N)
#define SIG_RAW_H_PACKEDBYTES POLYWH_PACKEDBYTES
#define SIG_RAW_PACKED_BYTES                               \
    (CHALLENGESEEDBYTES + Z1LEN * SIG_RAW_Z1_PACKEDBYTES + \
     EM * SIG_RAW_H_PACKEDBYTES)

