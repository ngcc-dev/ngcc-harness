/*
 * rans.h -- static byte-renormalized rANS entropy coder for SHUTTLE.
 *
 * Compresses the signature triple (seedC, z_1, hint) into the on-wire
 * `com` packet.  THREE static models (Q0, Qs, hint) coded into ONE merged
 * RANS_N-way interleaved byte stream; byte-exact between the Python golden
 * model (tools/rans.py) and this C reference.  See ref/rans.c for the
 * codec.
 *
 * REPRODUCIBLE CONSTANTS.  The tables in @@AUTOGEN:rans_tables@@ and the
 * meta in @@AUTOGEN:rans_meta@@ are emitted by reproducible Python
 * generators (DO NOT hand-edit a region; regenerate via `make tables`,
 * verify drift-free via `make check-consts`):
 *
 *   @@AUTOGEN:rans_tables@@ <- tools/gen_rans_tables.py
 *       THREE tables per param set: RANS_Q0_*, RANS_QS_*, RANS_HINT_*.
 *       Per table <T>:
 *         #define <T>_LO   (<int>)            symbol value of slot 0
 *         #define <T>_N    (<int>)            alphabet size (<= 256, uint8
 * SLOT) static const uint16_t <T>_FREQ[N];  sum == 1024, every entry >= 1
 *         static const uint16_t <T>_CDF[N+1]; prefix sums, CDF[0]=0,
 * CDF[N]=1024 static const uint32_t <T>_RCP[N];   Granlund-Montgomery
 * reciprocal static const uint8_t  <T>_RSH[N];   shift-1 static const
 * uint32_t <T>_BIAS[N];  start (or start+M-1 for freq==1) static const
 * uint8_t  <T>_SLOT[1024]; val->slot direct lookup (decoder)
 *
 *   @@AUTOGEN:rans_meta@@   <- tools/SigSize.py
 *       RANS_B0, RANS_BS (low-bit split widths) and RANS_RESERVED_BYTES
 *       (per-stream overflow reserve at 2^-35), per param set.
 *
 * CONSTANT-TIME POSTURE.  The codec runs on PUBLIC, post-signing data
 * (the signature IS the output; the secret y is gone by serialization
 * time).  So the data-dependent renorm `while` loops and `pos` bounds in
 * enc_put/dec_get are NOT a CT violation -- there is no secret-dependent
 * timing.  The ONLY adjacency is that the rANS out-of-support restart
 * count leaks the signing-attempt count, which the IRS/norm-gate abort
 * structure already exposes (documented, not hidden).
 */
