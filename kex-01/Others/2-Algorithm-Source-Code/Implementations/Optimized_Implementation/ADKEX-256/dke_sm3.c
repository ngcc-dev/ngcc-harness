/*
 * DKE-specific SM3 wrappers implementation.
 */
#include "dke_sm3.h"
#include "sm3.h"

/* The fixed HMAC key used by pseudohash functions.
 * key = SM3(UTF-8("3.14159265358979")) || SM3(UTF-8("2.71828182845904"))
 */
static const unsigned char dke_fixed_key[] = {
    0x53, 0x07, 0xf6, 0xd5, 0xeb, 0x6a, 0x3c, 0xed,
    0x3d, 0x24, 0xc5, 0x3c, 0xc9, 0xc8, 0x2c, 0xce,
    0x2f, 0x89, 0x36, 0x39, 0x70, 0x23, 0xf0, 0x69,
    0x5c, 0x26, 0xc8, 0x0c, 0x1a, 0xb1, 0x82, 0xa7,
    0x1d, 0xb0, 0x2b, 0xa9, 0x2f, 0x54, 0x40, 0x18,
    0x11, 0x5a, 0x96, 0xe7, 0x19, 0x66, 0x2c, 0xa3,
    0x2b, 0x7c, 0x7e, 0xfc, 0x0a, 0x6d, 0x24, 0x82,
    0x15, 0x07, 0x66, 0xba, 0x6f, 0x65, 0x5b, 0x8e
};

static const unsigned long long dke_fixed_key_len_bits = sizeof(dke_fixed_key) * 8;

int dke_hmac_with_fixed_key(const unsigned char *msg,
                            unsigned long long msg_len_bits,
                            unsigned char *mac) {
    return dke_sm3_hmac(msg, msg_len_bits,
                        dke_fixed_key, dke_fixed_key_len_bits, mac);
}
