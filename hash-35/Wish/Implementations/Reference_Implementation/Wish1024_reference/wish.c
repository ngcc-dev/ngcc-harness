byte GF_Mul(byte a, byte b){
  byte res = 0;
  for (; b; b >>= 1) {
    if (b & 1)  res ^= a;
    a = a << 1 ^ (a & 0x80 ? 0x1b : 0);
  }
  
  return res;
}

void SubBytes(lane s){
    for(unsigned i = 0; i < 16; ++i)
        s[i] = S_Box[s[i]];
}

void ShiftRows(lane s){
    lane temp = {0};
    for(unsigned row = 0; row < 4; ++row)
        for(unsigned col = 0; col < 4; ++col)
            temp[col*4 + row] = s[((col+row)%4)*4 + row];
    memcpy(s, temp, 16*sizeof(byte));
}

void MixColumns(lane s){
    lane temp = {0};
    for(unsigned col = 0; col < 4; ++col)
        for(unsigned row = 0; row < 4; ++row)
            for(unsigned r = 0; r < 4; ++r)
                temp[col*4 + row] ^= GF_Mul(MC_Matrix[row][r], s[col*4 + r]);
    memcpy(s, temp, 16*sizeof(byte));
}

void XOR(lane s, const lane c){
    for(unsigned i = 0; i < 16; ++i)
        s[i] ^= c[i];
}

void AESR(lane s){
    SubBytes(s);
    ShiftRows(s);
    MixColumns(s);
}

void Wish_hash(
    const unsigned digest_len_bits,
    const unsigned state_len_bits,
    const unsigned char *msg, 
    unsigned long long msg_len_bits, 
    unsigned char *digest
){
    
    // global parameters
    unsigned const block_len_bits = state_len_bits - digest_len_bits;
    unsigned const block_len_bytes = block_len_bits / 8;
    unsigned const state_len_bytes = state_len_bits / 8;
    unsigned const num_lanes = state_len_bits / 128;

    // select parameters that matches the state size
    const unsigned num_steps = (state_len_bits == 1024) ? 9 : 12;
    const int *mix = (state_len_bits == 1024) ? mix_1024 : mix_2048;


    // msg specific parameters
    unsigned msg_tail_bits = msg_len_bits % 8;
    unsigned long long msg_len_bytes = msg_len_bits / 8;
    unsigned long long num_blocks = msg_len_bits / block_len_bits + 1;
    

    // pad msg with '100...' to multiples of blocks
    lane *msg_padded = malloc(num_blocks * block_len_bytes);
    memset(msg_padded, 0, num_blocks  * block_len_bytes);
    memcpy(msg_padded, msg, msg_len_bytes);
    if (msg_tail_bits == 0) {
        ((byte*)msg_padded)[msg_len_bytes] = 0x80;
    } else {
        const unsigned char mask_input_bits = 0xff << (8 - msg_tail_bits);
        const unsigned char mask_append_bit = 0x80 >> msg_tail_bits;
        ((byte*)msg_padded)[msg_len_bytes] = (msg[msg_len_bytes] & mask_input_bits) | mask_append_bit;
    }


    // initialize the state: rate and capacity to all zeros
    lane *state = malloc(num_lanes * sizeof(lane));
    memset(state, 0x00, state_len_bytes);

    // process msg blocks
    for (unsigned long long blk = 0; blk < num_blocks; ++blk) {
        
        lane tweak = {0};
        lane *feedfwd = malloc(num_lanes / 2 * sizeof(lane));
        
        // encode the block number (at most 64bits long) into the tweak
        for (unsigned b = 0; b < 8; ++b)
            tweak[b] = (byte)(blk >> (b * 8));

        // absorb msg
        for (unsigned j = 0; j < num_lanes / 2; ++j)
            XOR(state[j], msg_padded[blk * num_lanes / 2 + j]);

        // add block separation constant if the last block
        if (blk == num_blocks - 1){
            lane theta = {0};
            theta[15] = 0x01;
            XOR(state[num_lanes-1], theta);
        }
        
        // save the feedforward value
        memcpy(feedfwd, &state[num_lanes / 2], num_lanes / 2 * sizeof(lane));


        // main loop for permutation
        for (unsigned step = 0; step < num_steps; ++step){
            // add tweak， always to the first lane of the capacity
            XOR(state[num_lanes / 2], tweak);


            // 1st AES round 
            for (unsigned j = 0; j < num_lanes; ++j){
                AESR(state[j]);
            }
            // 1st add constant, lane 0 only
            XOR(state[0], rcon[2 * step]);
            // 2nd AES round
            for (unsigned j = 0; j < num_lanes; ++j){
                AESR(state[j]);
            }
            // 2nd add constant, lane 0 only
            XOR(state[0], rcon[2 * step + 1]);

            // apply the mixing layer
            lane *temp = malloc(num_lanes * sizeof(lane));
            for (unsigned b = 0; b < num_lanes * 16; ++b)
                memcpy((byte *)temp + b, (byte *)state + mix[b], sizeof(byte));
            memcpy(state, temp, num_lanes * sizeof(lane));
            free(temp);
        }


        // XOR feedforward value to capacity
        for (unsigned j = num_lanes / 2; j < num_lanes; ++j)
            XOR(state[j], feedfwd[j - num_lanes / 2]);

        free(feedfwd);
    }

    // Squeeze: second half of the state is the digest output
    memcpy(digest, &state[num_lanes / 2], num_lanes / 2 * sizeof(lane));

    free(msg_padded);
    free(state);
}

