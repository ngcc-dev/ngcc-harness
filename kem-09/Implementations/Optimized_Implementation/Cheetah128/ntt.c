/**
 * @brief 5-point NTT/INTT implementation with stride support
 * @param in Input/output sequence (in-place operation)
 * @param stride Memory stride between consecutive elements
 * @param dir Direction: NTT_FORWARD for forward transform, NTT_INVERSE for inverse transform
 */
static void ntt_5(int16_t *in, int stride, ntt_direction_enum dir) {
    int32_t x[N2];
    int idx0 = 0;
    int idx1 = stride;
    int idx2 = 2 * stride;
    int idx3 = 3 * stride;
    int idx4 = 4 * stride;
    
    if (dir == NTT_FORWARD) {
        x[0] = (in[idx0] + in[idx1] + in[idx2] + in[idx3] + in[idx4]);
        x[1] = (in[idx0] + 4143 * in[idx1] + 5095 * in[idx2] + 1197 * in[idx3] + 4926 * in[idx4]);
        x[2] = (in[idx0] + 5095 * in[idx1] + 4926 * in[idx2] + 4143 * in[idx3] + 1197 * in[idx4]);
        x[3] = (in[idx0] + 1197 * in[idx1] + 4143 * in[idx2] + 4926 * in[idx3] + 5095 * in[idx4]);
        x[4] = (in[idx0] + 4926 * in[idx1] + 1197 * in[idx2] + 5095 * in[idx3] + 4143 * in[idx4]);  
    } else {
        x[0] = (in[idx0] + in[idx1] + in[idx2] + in[idx3] + in[idx4]);
        x[1] = (in[idx0] + 4926 * in[idx1] + 1197 * in[idx2] + 5095 * in[idx3] + 4143 * in[idx4]);
        x[2] = (in[idx0] + 1197 * in[idx1] + 4143 * in[idx2] + 4926 * in[idx3] + 5095 * in[idx4]);
        x[3] = (in[idx0] + 5095 * in[idx1] + 4926 * in[idx2] + 4143 * in[idx3] + 1197 * in[idx4]);
        x[4] = (in[idx0] + 4143 * in[idx1] + 5095 * in[idx2] + 1197 * in[idx3] + 4926 * in[idx4]);
    }
    in[idx0] = mod_q(x[0]);
    in[idx1] = mod_q(x[1]);
    in[idx2] = mod_q(x[2]);
    in[idx3] = mod_q(x[3]);
    in[idx4] = mod_q(x[4]);
}

static void ntt_128(int16_t x[N1], ntt_direction_enum dir) {
    const int16_t* tw = (dir == NTT_FORWARD) ? w1_pow : w1_inv_pow;
    int32_t b[128]; 

    // Bit-reversal
    for (int i = 0; i < 128; ++i) {
        b[i] = x[bit_reverse_table[i]];
    }

    // Layer m=1 (step=2)
    #define BF2(i) do { \
        int32_t u = b[i], v = b[i+1]; \
        int32_t vw = mod_q(v * tw[0]); \
        b[i] = (u + vw); \
        b[i+1] = (u - vw); \
    } while(0)
    for (int i = 0; i < 128; i += 2) BF2(i);

    // Layer m=2 (step=4, tw_stride=32)
    #define BF4(i, j) do { \
        int32_t u = b[i+j], v = b[i+j+2]; \
        int32_t vw = mod_q(v * tw[32*j]); \
        b[i+j] = (u + vw); \
        b[i+j+2] = (u - vw); \
    } while(0)
    for (int i = 0; i < 128; i += 4) { BF4(i,0); BF4(i,1); }

    // Layer m=3 (step=8, tw_stride=16)
    #define BF8(i, j) do { \
        int32_t u = b[i+j], v = b[i+j+4]; \
        int32_t vw = mod_q(v * tw[16*j]); \
        b[i+j] = (u + vw); \
        b[i+j+4] = (u - vw); \
    } while(0)
    for (int i = 0; i < 128; i += 8) { BF8(i,0); BF8(i,1); BF8(i,2); BF8(i,3); }

    // Layer m=4 (step=16, tw_stride=8)
    #define BF16(i, j) do { \
        int32_t u = b[i+j], v = b[i+j+8]; \
        int32_t vw = mod_q(v * tw[8*j]); \
        b[i+j] = (u + vw); \
        b[i+j+8] = (u - vw); \
    } while(0)
    for (int i = 0; i < 128; i += 16) {
        BF16(i,0); BF16(i,1); BF16(i,2); BF16(i,3);
        BF16(i,4); BF16(i,5); BF16(i,6); BF16(i,7);
    }

    // Layer m=5 (step=32, tw_stride=4)
    #define BF32(i, j) do { \
        int32_t u = b[i+j], v = b[i+j+16]; \
        int32_t vw = mod_q(v * tw[4*j]); \
        b[i+j] = (u + vw); \
        b[i+j+16] = (u - vw); \
    } while(0)
    for (int i = 0; i < 128; i += 32) {
        for (int j = 0; j < 16; j++) BF32(i, j);
    }

    // Layer m=6 (step=64, tw_stride=2)
    #define BF64(i, j) do { \
        int32_t u = b[i+j], v = b[i+j+32]; \
        int32_t vw = mod_q(v * tw[2*j]); \
        b[i+j] = (u + vw); \
        b[i+j+32] = (u - vw); \
    } while(0)
    for (int i = 0; i < 128; i += 64) {
        for (int j = 0; j < 32; j++) BF64(i, j);
    }

    // Layer m=7 (step=128, tw_stride=1)
    #define BF128(j) do { \
        int32_t u = b[j], v = b[j+64]; \
        int32_t vw = mod_q(v * tw[1*j]); \
        b[j] = (u + vw); \
        b[j+64] = (u - vw); \
    } while(0)
    for (int j = 0; j < 64; j++) BF128(j);

    for (int i = 0; i < 128; ++i) {
        x[i] = mod_q(b[i]);
    }
}

/**
 * @brief Unified 640-point GT-NTT/INTT implementation (optimized version with reduced intermediate variables)
 * @param x Input/output sequence (in-place operation), array of N integers
 * @param dir Direction: NTT_FORWARD for forward transform / NTT_INVERSE for inverse transform
 */
void ntt_640(int16_t *x, ntt_direction_enum dir) {
    if (dir == NTT_FORWARD) {
        // Pre-multiplication with psi powers for forward NTT
        for (int i = 0; i < N; i++) {
            x[i] = mod_q(psi_pow_table[i]*x[i]);
        }   
    }

    // Step 1: CRT mapping to 1D matrix
    int16_t mat_1d[N];
    for (int i = 0; i < N; i++) {
        mat_1d[i] = x[ctr_map_table[i]];
    }

    // Step 2: 128-point unified NTT/INTT along row direction
    // Process each column: apply 128-point NTT/INTT to rows of the matrix
    for (int16_t n2 = 0U; n2 < N2; n2++) {
        ntt_128(mat_1d+n2*N1, dir); // Process rows directly in the matrix
    }

    // Step 3: 5-point unified NTT/INTT along column direction
    // Process each row: apply 5-point NTT/INTT to columns of the matrix
    for (int16_t n1 = 0U; n1 < N1; n1++) {
        ntt_5(mat_1d+n1, N1, dir); // Process columns directly in the matrix
    }

    // Step 4: Inverse CRT mapping + overall scaling for 640-point inverse transform
    // crt_unmap_1d(mat_1d, x);
    for (int i = 0; i < N; i++) {
        x[ctr_map_table[i]] = mat_1d[i];
    }

    if (dir == NTT_INVERSE) {
        // Post-multiplication with inverse psi powers for inverse NTT
        for (int i = 0; i < N; i++) {
            x[i] = mod_q(invpsi_pow_table[i]*x[i]);
        }   
    }
}
