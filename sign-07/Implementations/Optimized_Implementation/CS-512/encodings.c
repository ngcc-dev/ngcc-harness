/*************************************************
* Name:        pkEncode
*
* Description: Bit-pack public key pk = (rho, t1).
*
* Arguments:   - uint8_t pk[]: output byte array
*              - const uint8_t rho[]: byte array containing rho
*              - const poly *t1: pointer to vector b
**************************************************/
void pkEncode(uint8_t pk[PUBLICKEYBYTES],
              const uint8_t rho[SEEDBYTES],
              const poly* t1)
{
    int i;

    for (i = 0; i < SEEDBYTES; ++i) { pk[i] = rho[i]; }

    pk += SEEDBYTES;
    for (i = 0; i < k; ++i)
        SimpleBitPack(pk + i * POLYT1_PACKEDBYTES, &t1[i], bq - beta);
}

/*************************************************
* Name:        pkDecode
*
* Description: Unpack public key pk = (rho, t1).
*
* Arguments:   - const uint8_t rho[]: output byte array for rho
*              - const poly *t1: pointer to output vector b
*              - uint8_t pk[]: byte array containing bit-packed pk
**************************************************/
void pkDecode(uint8_t rho[SEEDBYTES],
              poly* t1,
              const uint8_t pk[PUBLICKEYBYTES])
{
    int i;

    for (i = 0; i < SEEDBYTES; ++i) { rho[i] = pk[i]; }
    
    pk += SEEDBYTES;
    for (i = 0; i < k; ++i)
        SimpleBitUnpack(&t1[i], pk + i * POLYT1_PACKEDBYTES, bq - beta);
}

/*************************************************
* Name:        skEncode
*
* Description: Bit-pack secret key sk = (pk, K, tr, s, e, t0, t1).
*
* Arguments:   - uint8_t sk[]: output byte array
*              - const uint8_t pk[]: byte array containing pk
*              - const uint8_t K[]: byte array containing K
*              - const uint8_t tr[]: byte array containing H(pk)
*              - const poly *s: pointer to vector s
*              - const poly *e: pointer to vector e
*              - const poly *t0: pointer to vector t0
*              - const poly *t1: pointer to vector t1
* 
**************************************************/
void skEncode(uint8_t sk[SECRETKEYBYTES],
              const uint8_t rho[SEEDBYTES],
              const uint8_t K[SEEDBYTES],
              const uint8_t tr[HBYTES],
              const poly* s0,
              const poly* e,
              const poly* t0,
              const poly* t1)
{
    int i;

    for (i = 0; i < SEEDBYTES; ++i) { sk[i] = rho[i]; }
    sk += SEEDBYTES;

    for (i = 0; i < SEEDBYTES; ++i) { sk[i] = K[i]; }
    sk += SEEDBYTES;

    for (i = 0; i < HBYTES; ++i) { sk[i] = tr[i]; }
    sk += HBYTES;

    for (i = 0; i < l; ++i)
        BitPack(sk + i * POLYETA_PACKEDBYTES, &s0[i], eta);
    sk += l * POLYETA_PACKEDBYTES;

    for (i = 0; i < k; ++i)
        BitPack(sk + i * POLYETA_PACKEDBYTES, &e[i], eta);
    sk += k * POLYETA_PACKEDBYTES;

    for (i = 0; i < k; ++i)
        BitPack(sk + i * POLYT0_PACKEDBYTES, &t0[i], beta);
    sk += k * POLYT0_PACKEDBYTES;

    for (i = 0; i < k; ++i)
        SimpleBitPack(sk + i * POLYT1_PACKEDBYTES, &t1[i], bq - beta);
}

/*************************************************
* Name:        skDecode
*
* Description: Unpack secret key sk = (rho, K, tr, s, t0, t1).
*
* Arguments:   - uint8_t rho[]: output byte array for rho
*              - uint8_t K[]: output byte array for K
*              - uint8_t tr[]: output byte array for tr
*              - poly *s: pointer to vector s = (s, e)
*              - poly *t0: pointer to vector t0
*              - poly *t1: pointer to vector t1
*              - const uint8_t sk[]: byte array containing bit-packed sk
* 
**************************************************/
void skDecode(uint8_t rho[SEEDBYTES],
              uint8_t K[SEEDBYTES],
              uint8_t tr[HBYTES],
              poly* s,
              poly* t0,
              poly* t1,
              const uint8_t sk[SECRETKEYBYTES])
{
    int i;

    for (i = 0; i < SEEDBYTES; ++i) { rho[i] = sk[i]; }
    sk += SEEDBYTES;

    for (i = 0; i < SEEDBYTES; ++i) { K[i] = sk[i]; }
    sk += SEEDBYTES;

    for (i = 0; i < HBYTES; ++i) { tr[i] = sk[i]; }
    sk += HBYTES;

    for (i = 0; i < l; ++i)
        BitUnpack(&s[i], sk + i * POLYETA_PACKEDBYTES, eta);
    sk += l * POLYETA_PACKEDBYTES;

    for (i = 0; i < k; ++i)
        BitUnpack(&s[i + l], sk + i * POLYETA_PACKEDBYTES, eta);
    sk += k * POLYETA_PACKEDBYTES;

    for (i = 0; i < k; ++i)
        BitUnpack(&t0[i], sk + i * POLYT0_PACKEDBYTES, beta);
    sk += k * POLYT0_PACKEDBYTES;

    for (i = 0; i < k; ++i)
        SimpleBitUnpack(&t1[i], sk + i * POLYT1_PACKEDBYTES, bq - beta);
}

