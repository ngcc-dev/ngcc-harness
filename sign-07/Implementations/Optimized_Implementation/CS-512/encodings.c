/*************************************************
 * Name:        encode_rans
 *
 * Description: rANS encode polynomial vector
 *
 * Arguments:   - uint8_t *buf: pointer to output buffer
 *              - const int32_t *z: pointer to polynomial vector
 *HighBits(z1)
 **************************************************/
int32_t encode_rans(uint8_t* buf, const int32_t* z, int cnum, const RansEncSymbol* esyms, int num) 
{
    int16_t s;
    uint8_t* ptr;
    RansState rans;
    size_t size_encoded;
    uint8_t encoding[(k + l) * n];

    RansEncInit(&rans);
    ptr = encoding + cnum; // end of output buffer

    for (size_t i = cnum; i > 0; i--) {
        s = z[i - 1] + num / 2; // from centered to positive representation
        RansEncPutSymbol(&rans, &ptr, &esyms[s]);
    }

    RansEncFlush(&rans, &ptr);

    size_encoded = encoding + cnum - ptr;
    memcpy(buf, ptr, size_encoded);
    return (int32_t)size_encoded;
}

/*************************************************
 * Name:        decode_rans
 *
 * Description: rANS decode polynomial vector
 *
 * Arguments:   - int32_t *z: pointer to polynomial vector
 *              - const uint8_t *buf: pointer to output buffer
 **************************************************/
static int decode_rans(int32_t* z, int cnum, const uint8_t* buf, int len, 
    const RansDecSymbol* dsyms, int num, const uint8_t* symbol, int scale_bits) 
{
    uint8_t s;
    RansState rans;
    size_t size_used;
    const uint8_t* buf_start = buf;
    const uint8_t* buf_end = buf + len;

    if (RansDecInit(&rans, (uint8_t**)&buf))
        return 1;

    for (size_t i = 0; i < cnum; i++) {
        s = symbol[RansDecGet(&rans, scale_bits)];
        z[i] = s - num / 2; // from positive to centered representation
        RansDecAdvanceSymbol(&rans, (uint8_t**)&buf, buf_end, &dsyms[s], scale_bits);
    }

    if (RansDecVerify(&rans)) {
        return 1;//final state not correct
    }

    size_used = buf - buf_start;
    if (size_used != len) {
        return 1;//size does not match
    }
    return 0;
}

/*************************************************
* Name:        sigEncode
*
* Description: Bit-pack signature sig = (cwave, z).
*
* Arguments:   - uint8_t sig[]: output byte array
*              - const uint8_t *cwave: pointer to challenge hash length HBYTES bytes
*              - const poly *z: pointer to vector z
**************************************************/
int sigEncode(uint8_t sig[SIGNATUREBYTES],
              const uint8_t* cwave,
              const poly* z)
{
    poly low[l];
    int32_t i, hi[l * n], cnt;
    uint8_t buf[2 * POLYZ2_PACKEDBYTES];

    for (i = 0; i < POLYC_PACKEDBYTES; ++i) { sig[i] = cwave[i]; }
    sig += POLYC_PACKEDBYTES;

#if d0 == 0
    memset(sig, 0, POLYZ0H_PACKEDBYTES);
    cnt = encode_rans(sig + 2, (int32_t*)&z[0], n, esyms_z0, M_HB_Z0);
#else
    DecomposeVector(hi, low, &z[0], 1, d0);
    BitPack(sig, &low[0], d0);
    sig += POLYZ0L_PACKEDBYTES;
    memset(sig, 0, POLYZ0H_PACKEDBYTES);
    cnt = encode_rans(sig + 2, hi, n, esyms_z0, M_HB_Z0);
#endif
    if (cnt > POLYZ0H_PACKEDBYTES - 2)
        return 1;
    memcpy(sig, (uint8_t*)&cnt, 2);
    sig += POLYZ0H_PACKEDBYTES;

    DecomposeVector(hi, low, z + 1, l, d1);
    for (i = 0; i < l; ++i) {
        BitPack(sig, &low[i], d1);
        sig += POLYZ1L_PACKEDBYTES;
    }
    memset(sig, 0, POLYZ1H_PACKEDBYTES);
    cnt = encode_rans(sig + 2, hi, l * n, esyms_hb_z1, M_HB_Z1);
    if (cnt > POLYZ1H_PACKEDBYTES - 2) 
        return 1;    
    memcpy(sig, (uint8_t*)&cnt, 2);
    sig += POLYZ1H_PACKEDBYTES;

    memset(sig, 0, POLYZ2_PACKEDBYTES);
    cnt = encode_rans(buf, (int32_t*)&z[l + 1], k * n, esyms_z2, M_HB_Z2);
    if (cnt > POLYZ2_PACKEDBYTES - 2)
        return 1;
    memcpy(sig + 2, buf, cnt);
    memcpy(sig, (uint8_t*)&cnt, 2);

    return 0;
}

/*************************************************
* Name:        sigDecode
*
* Description: Unpack signature sig = (cwave, z).
*
* Arguments:   - uint8_t *cwave: pointer to output challenge hash
*              - poly *z: pointer to output vector z
*              - const uint8_t sig[]: byte array containing bit-packed signature
*
**************************************************/
int sigDecode(uint8_t* cwave,
              poly* z,
              const uint8_t sig[SIGNATUREBYTES])
{
    poly low[l];
    int32_t i, hi[l * n], cnt = 0;

    for (i = 0; i < POLYC_PACKEDBYTES; ++i) { cwave[i] = sig[i]; }
    sig += POLYC_PACKEDBYTES;

#if d0 == 0
    memcpy((int32_t*)&cnt, sig, 2);
    if (decode_rans((int32_t*)&z[0], n, sig + 2, cnt, dsyms_z0, M_HB_Z0, symbol_z0, SCALE_BITS))
        return 1;
#else
    BitUnpack(&low[0], sig, d0);
    sig += POLYZ0L_PACKEDBYTES;
    memcpy((int32_t*)&cnt, sig, 2);
    if (decode_rans(hi, n, sig + 2, cnt, dsyms_z0, M_HB_Z0, symbol_z0, SCALE_BITS))
        return 1;
    ComposeVector(&z[0], &low[0], hi, 1, d0);
#endif
    sig += POLYZ0H_PACKEDBYTES;

    for (i = 0; i < l; ++i) {
        BitUnpack(&low[i], sig, d1);
        sig += POLYZ1L_PACKEDBYTES;
    }
    memcpy((int32_t*)&cnt, sig, 2);
    if (decode_rans(hi, l * n, sig + 2, cnt, dsyms_hb_z1, M_HB_Z1, symbol_hb_z1, SCALE_BITS))
        return 1;
    sig += POLYZ1H_PACKEDBYTES;

    ComposeVector(z + 1, low, hi, l, d1);

    memcpy((int32_t*)&cnt, sig, 2);
    if (decode_rans((int32_t*)&z[l + 1], k * n, sig + 2, cnt, dsyms_z2, M_HB_Z2, symbol_z2, SCALE_BITS - 1))
        return 1;

    return 0;
}

