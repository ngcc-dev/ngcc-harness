static inline void
gm_tab(double *re, double *im, size_t k)
{
	*re = yykg_gm_tab[(k << 1) + 0u];
	*im = yykg_gm_tab[(k << 1) + 1u];
}

static inline yykg_cplx
c_mul_gm(yykg_cplx a, double b_re, double b_im)
{
	return yykg_c_make(
		a.re * b_re - a.im * b_im,
		a.re * b_im + a.im * b_re);
}

void
yykg_fft(double *f, unsigned logn)
{
	size_t n, hn, t, m;

	n = (size_t)1u << logn;
	hn = n >> 1;
	t = hn;
	for (unsigned u = 1, m1 = 2; u < logn; u++, m1 <<= 1) {
		size_t ht, hm, i1, j1;

		ht = t >> 1;
		m = (size_t)m1;
		hm = m >> 1;
		for (i1 = 0, j1 = 0; i1 < hm; i1++, j1 += t) {
			size_t j, j2;
			double s_re, s_im;

			j2 = j1 + ht;
			gm_tab(&s_re, &s_im, m + i1);
			for (j = j1; j < j2; j++) {
				yykg_cplx x, y, z;

				x = yykg_c_make(f[j], f[j + hn]);
				y = yykg_c_make(f[j + ht], f[j + ht + hn]);
				z = c_mul_gm(y, s_re, s_im);
				f[j] = x.re + z.re;
				f[j + hn] = x.im + z.im;
				f[j + ht] = x.re - z.re;
				f[j + ht + hn] = x.im - z.im;
			}
		}
		t = ht;
	}
}

void
yykg_ifft(double *f, unsigned logn)
{
	size_t n, hn, t, m;

	n = (size_t)1u << logn;
	t = 1;
	m = n;
	hn = n >> 1;
	for (unsigned u = logn; u > 1; u--) {
		size_t hm, dt, i1, j1;

		hm = m >> 1;
		dt = t << 1;
		for (i1 = 0, j1 = 0; j1 < hn; i1++, j1 += dt) {
			size_t j, j2;
			double s_re, s_im;

			j2 = j1 + t;
			gm_tab(&s_re, &s_im, hm + i1);
			s_im = -s_im;
			for (j = j1; j < j2; j++) {
				yykg_cplx x, y, sum, diff, z;

				x = yykg_c_make(f[j], f[j + hn]);
				y = yykg_c_make(f[j + t], f[j + t + hn]);
				sum = yykg_c_add(x, y);
				diff = yykg_c_sub(x, y);
				z = c_mul_gm(diff, s_re, s_im);
				f[j] = sum.re;
				f[j + hn] = sum.im;
				f[j + t] = z.re;
				f[j + t + hn] = z.im;
			}
		}
		t = dt;
		m = hm;
	}

	if (logn > 0) {
		double scale;

		scale = yykg_p2_tab[logn];
		for (size_t u = 0; u < n; u++) {
			f[u] *= scale;
		}
	}
}

void
yykg_poly_split_fft(double *restrict f0, double *restrict f1,
	const double *restrict f, unsigned logn)
{
	size_t n, hn, qn;

	/*
	 * Falcon poly_split_fft() in the packed FFT representation:
	 * real parts occupy f[0..n/2-1], imaginary parts occupy f[n/2..n-1].
	 * The split represents f(X) = f0(X^2) + X*f1(X^2) while staying in FFT.
	 */
	n = (size_t)1u << logn;
	hn = n >> 1;
	if (logn == 1u) {
		f0[0] = f[0];
		f1[0] = f[hn];
		return;
	}

	qn = hn >> 1;
	for (size_t u = 0; u < qn; u++) {
		double a_re, a_im, b_re, b_im, t_re, t_im, s_re, s_im;

		a_re = f[(u << 1) + 0u];
		a_im = f[(u << 1) + 0u + hn];
		b_re = f[(u << 1) + 1u];
		b_im = f[(u << 1) + 1u + hn];

		f0[u] = 0.5 * (a_re + b_re);
		f0[u + qn] = 0.5 * (a_im + b_im);

		t_re = 0.5 * (a_re - b_re);
		t_im = 0.5 * (a_im - b_im);
		gm_tab(&s_re, &s_im, u + hn);
		f1[u] = t_re * s_re + t_im * s_im;
		f1[u + qn] = t_im * s_re - t_re * s_im;
	}
}

void
yykg_poly_to_fft_i8(double dst[YUANYANG_D], const int8_t src[YUANYANG_D])
{
	for (size_t u = 0; u < YUANYANG_D; u++) {
		dst[u] = (double)src[u];
	}
	yykg_fft(dst, YUANYANG_LOGD);
}

void
yykg_poly_to_fft_double(
	double dst[YUANYANG_D], const double src[YUANYANG_D])
{
	memcpy(dst, src, sizeof(double) * YUANYANG_D);
	yykg_fft(dst, YUANYANG_LOGD);
}

void
yykg_poly_from_fft(double dst[YUANYANG_D], const double src_fft[YUANYANG_D])
{
	memcpy(dst, src_fft, sizeof(double) * YUANYANG_D);
	yykg_ifft(dst, YUANYANG_LOGD);
}
