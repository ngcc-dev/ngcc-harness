# 3. Exact H^sim degree law on a small supersingular isogeny graph
# --------------------------------------------------------------------------
# B = Q<i, j> with i^2 = -1, j^2 = -p, k = ij, p = 3 mod 4.  The maximal order
# O0 = Z + Z i + Z (i+j)/2 + Z (1+k)/2 is End(E0), j(E0) = 1728.  Left
# O0-ideal classes are the supersingular curves, and Hom(E_I, E_J) is the
# lattice conj(I) J with deg = nrd / (N(I) N(J)).  Elements are stored in
# doubled coordinates: (a, b, c, d) means (a + b i + c j + d k) / 2.

O0 = ((2, 0, 0, 0), (0, 2, 0, 0), (0, 1, 1, 0), (1, 0, 0, 1))


def product(x, y, p):
    """Doubled coordinates of x y for two elements of O0."""
    a0, a1, a2, a3 = x
    b0, b1, b2, b3 = y
    z = (a0 * b0 - a1 * b1 - p * (a2 * b2 + a3 * b3),
         a0 * b1 + a1 * b0 + p * (a2 * b3 - a3 * b2),
         a0 * b2 + a2 * b0 + a3 * b1 - a1 * b3,
         a0 * b3 + a3 * b0 + a1 * b2 - a2 * b1)
    assert not any(c & 1 for c in z)
    return tuple(c >> 1 for c in z)


def conjugate(x):
    return (x[0], -x[1], -x[2], -x[3])


def four_norm(x, p):
    return x[0] ** 2 + x[1] ** 2 + p * (x[2] ** 2 + x[3] ** 2)   # 4 nrd(x)


def hermite(rows):
    """Canonical basis (row Hermite normal form) of a rank-4 integer lattice."""
    rows = [list(r) for r in rows if any(r)]
    basis = []
    for col in range(4):
        while True:
            live = [r for r in rows if r[col]]
            if len(live) <= 1:
                break
            pivot = min(live, key=lambda r: abs(r[col]))
            for r in live:
                if r is not pivot:
                    f = r[col] // pivot[col]
                    for t in range(col, 4):
                        r[t] -= f * pivot[t]
        live = [r for r in rows if r[col]]
        assert live, "lattice is not of full rank"
        pivot = live[0]
        rows = [r for r in rows if r is not pivot and any(r)]
        basis.append([-c for c in pivot] if pivot[col] < 0 else pivot)
    assert not rows
    for a in range(1, 4):
        for b in range(a):
            f = basis[b][a] // basis[a][a]
            for t in range(a, 4):
                basis[b][t] -= f * basis[a][t]
    return tuple(tuple(r) for r in basis)


def index_in_order(basis):
    return basis[0][0] * basis[1][1] * basis[2][2] * basis[3][3] // 4


def degree_form(ideal_i, ideal_j, p):
    """Reduced integer matrix A with deg(z) = z^T A z / 2 on Hom(E_i, E_j)."""
    (basis_i, norm_i), (basis_j, norm_j) = ideal_i, ideal_j
    m = hermite([product(conjugate(u), v, p) for u in basis_i for v in basis_j])
    scale = 2 * norm_i * norm_j
    form = [[0] * 4 for _ in range(4)]
    for a in range(4):
        for b in range(4):
            t = (m[a][0] * m[b][0] + m[a][1] * m[b][1]
                 + p * (m[a][2] * m[b][2] + m[a][3] * m[b][3]))
            assert t % scale == 0
            form[a][b] = t // scale
    assert all(form[a][a] % 2 == 0 for a in range(4))
    changed = True
    while changed:                           # pairwise size reduction
        changed = False
        for a in range(4):
            for b in range(4):
                if a != b and 2 * abs(form[a][b]) > form[b][b]:
                    f = (2 * form[a][b] + form[b][b]) // (2 * form[b][b])
                    for t in range(4):
                        form[a][t] -= f * form[b][t]
                    for t in range(4):
                        form[t][a] -= f * form[t][b]
                    changed = True
    order = sorted(range(4), key=lambda a: form[a][a])
    return [[form[a][b] for b in order] for a in order]


def determinant(matrix):
    m = [[Fraction(x) for x in row] for row in matrix]
    det = Fraction(1)
    for c in range(4):
        pivot = next((r for r in range(c, 4) if m[r][c]), None)
        if pivot is None:
            return Fraction(0)
        if pivot != c:
            m[c], m[pivot] = m[pivot], m[c]
            det = -det
        det *= m[c][c]
        for r in range(c + 1, 4):
            f = m[r][c] / m[c][c]
            for t in range(c, 4):
                m[r][t] -= f * m[c][t]
    return det


def count_degrees(form, bound):
    """counts[n] = number of z in Z^4 with z^T form z / 2 = n, 0 <= n <= bound.

    The three outer ranges come from a floating-point Cholesky decomposition
    with slack; the innermost range and every degree are exact integers.
    """
    q = [[form[a][b] / 2 for b in range(4)] for a in range(4)]
    d = [0.0] * 4
    mu = [[0.0] * 4 for _ in range(4)]
    for a in range(4):
        d[a] = q[a][a]
        for b in range(a + 1, 4):
            mu[a][b] = q[a][b] / d[a]
        for b in range(a + 1, 4):
            for c in range(a + 1, 4):
                q[b][c] -= mu[a][b] * q[a][c]
    counts = [0] * (bound + 1)
    a0, a1, a2, a3 = (form[a][a] // 2 for a in range(4))
    f01, f02, f03 = form[0][1], form[0][2], form[0][3]
    f12, f13, f23 = form[1][2], form[1][3], form[2][3]
    slack = 1e-6
    for z3 in range(int(math.sqrt(bound / d[3]) + slack) + 1):
        weight = 2 if z3 else 1              # z and -z have the same degree
        left3 = bound - d[3] * z3 * z3
        centre2 = -mu[2][3] * z3
        width2 = math.sqrt(max(left3, 0.0) / d[2]) + slack
        for z2 in range(math.ceil(centre2 - width2),
                        math.floor(centre2 + width2) + 1):
            left2 = left3 - d[2] * (z2 - centre2) ** 2
            centre1 = -(mu[1][2] * z2 + mu[1][3] * z3)
            width1 = math.sqrt(max(left2, 0.0) / d[1]) + slack
            tail = a2 * z2 * z2 + a3 * z3 * z3 + f23 * z2 * z3
            for z1 in range(math.ceil(centre1 - width1),
                            math.floor(centre1 + width1) + 1):
                beta = f01 * z1 + f02 * z2 + f03 * z3
                gamma = tail + z1 * (a1 * z1 + f12 * z2 + f13 * z3)
                # degree = a0 t^2 + beta t + gamma <= bound, t = z0
                disc = beta * beta - 4 * a0 * (gamma - bound)
                if disc < 0:
                    continue
                root = isqrt(disc)
                for t in range(-((root + beta) // (2 * a0)),
                               (root - beta) // (2 * a0) + 1):
                    counts[gamma + t * (beta + a0 * t)] += weight
    return counts


def ideal_classes(p, ell=3):
    """One left O0-ideal per class, by breadth-first search on ell-isogenies.

    The ell-isogeny graph is connected; the search stops when the Eichler
    mass formula sum 1/|Aut(E)| = (p - 1)/24 is met.
    """
    start = (hermite(O0), 1)
    classes = [start]
    units = [count_degrees(degree_form(start, start, p), 1)[1]]
    mass, target = Fraction(1, units[0]), Fraction(p - 1, 24)
    done = 0
    while done < len(classes) and mass != target:
        basis, norm = classes[done]
        done += 1
        neighbours = set()
        for y in itertools.product(range(ell), repeat=4):
            if len(neighbours) == ell + 1:
                break
            x = tuple(sum(y[t] * basis[t][c] for t in range(4)) for c in range(4))
            if not any(y) or (four_norm(x, p) // (4 * norm)) % ell:
                continue
            sub = hermite([product(e, x, p) for e in O0]
                          + [tuple(ell * c for c in b) for b in basis])
            if sub in neighbours:
                continue
            neighbours.add(sub)
            ideal = (sub, ell * norm)
            assert index_in_order(sub) == (ell * norm) ** 2
            if any(count_degrees(degree_form(ideal, known, p), 1)[1]
                   for known in classes):
                continue                     # a degree-1 map: same class
            classes.append(ideal)
            units.append(count_degrees(degree_form(ideal, ideal, p), 1)[1])
            mass += Fraction(1, units[-1])
        assert len(neighbours) == ell + 1
    return classes, units, mass == target


def tv_to_weights(law, total, weights, degrees):
    weight_total = sum(weights[n >> 1] for n in degrees)
    return float(Fraction(
        sum(abs(law[n] * weight_total - weights[n >> 1] * total)
            for n in degrees),
        2 * total * weight_total,
    ))


def hsim_laws(counts, units, degrees):
    """Exact degree law of H^sim for each start curve E1.

    E2 is stationary (probability proportional to 1/|Aut(E2)|) and phi_2 is
    uniform among the counted maps E1 -> E2.  Returns integer numerators and
    their common total for each E1.
    """
    h = len(units)
    laws = []
    for i in range(h):
        per_target = [sum(counts[i][j][n] for n in degrees) for j in range(h)]
        assert all(per_target), "H^sim would return the failure symbol"
        common = math.lcm(*per_target)
        factor = [(12 // units[j]) * (common // per_target[j]) for j in range(h)]
        law = {n: sum(factor[j] * counts[i][j][n] for j in range(h))
               for n in degrees}
        laws.append((law, sum(law.values())))
    return laws


def toy_graph(p, bound, sigma, psi):
    classes, units, mass_ok = ideal_classes(p)
    h = len(classes)
    counts = [[None] * h for _ in range(h)]
    determinants_ok = True
    points = 0
    for i in range(h):
        for j in range(i, h):
            form = degree_form(classes[i], classes[j], p)
            determinants_ok &= determinant(form) == p * p
            counts[i][j] = counts[j][i] = count_degrees(form, bound - 1)
            points += sum(counts[i][j])
    units_ok = all(counts[j][j][1] == units[j] for j in range(h))
    # Odd degrees below the bound.  Degrees divisible by p (inseparable maps)
    # are left out: the toy bound exceeds p, the submitted D_rsp does not.
    degrees = [n for n in range(1, bound, 2) if n % p]
    # Each subgroup of order n of E_i is the kernel of |Aut(E_j)| maps.
    twelfths = [12 // u for u in units]      # 12 / |Aut(E_j)|; |Aut| is 2, 4, 6
    row_sums_ok = all(u * w == 12 for u, w in zip(units, twelfths)) and all(
        sum(w * c[n] for w, c in zip(twelfths, counts[i]))
        == 12 * sigma[n >> 1]
        for i in range(h) for n in degrees
    )
    # Maps with cyclic kernel are the primitive lattice vectors.
    mobius = {}
    for c in range(1, isqrt(bound) + 1, 2):
        factors = [q for q in range(3, c + 1, 2)
                   if c % q == 0 and all(q % r for r in range(3, q, 2))]
        if all(c % (q * q) for q in factors):
            mobius[c] = (-1) ** len(factors)
    terms = {n: [(sign, n // (c * c)) for c, sign in mobius.items()
                 if n % (c * c) == 0] for n in degrees}
    cyclic = [[None] * h for _ in range(h)]
    for i in range(h):
        for j in range(i, h):
            source, row = counts[i][j], [0] * bound
            for n in degrees:
                row[n] = sum(sign * source[m] for sign, m in terms[n])
            cyclic[i][j] = cyclic[j][i] = row

    def summary(table):
        laws = hsim_laws(table, units, degrees)
        to_sigma = [tv_to_weights(law, total, sigma, degrees) for law, total in laws]
        to_psi = [tv_to_weights(law, total, psi, degrees) for law, total in laws]
        nine = [float(Fraction(sum(law[n] for n in degrees if n % 9 == 0), total))
                for law, total in laws]
        return {
            "tv_to_sigma_law_max_over_e1": max(to_sigma),
            "tv_to_sigma_law_min_over_e1": min(to_sigma),
            "tv_to_psi_law_max_over_e1": max(to_psi),
            "tv_to_psi_law_min_over_e1": min(to_psi),
            "pr_9_divides_d_max_over_e1": max(nine),
            "pr_9_divides_d_min_over_e1": min(nine),
        }

    sum_sigma = sum(sigma[n >> 1] for n in degrees)
    sum_psi = sum(psi[n >> 1] for n in degrees)
    row = {
        "prime": p,
        "odd_degrees_below": bound,
        "degrees_divisible_by_p_excluded": True,
        "classes": h,
        "automorphism_group_orders": sorted(units),
        "lattice_points_enumerated": points,
        "hsim_all_isogenies": summary(counts),
        "hsim_cyclic_isogenies_only": summary(cyclic),
        "tv_sigma_law_to_psi_law": tv_to_weights(
            {n: sigma[n >> 1] for n in degrees}, sum_sigma, psi, degrees),
        "pr_9_divides_d_sigma_law":
            sum(sigma[n >> 1] for n in degrees if n % 9 == 0) / sum_sigma,
        "pr_9_divides_d_psi_law":
            sum(psi[n >> 1] for n in degrees if n % 9 == 0) / sum_psi,
    }
    structure_ok = mass_ok and determinants_ok and units_ok
    return row, structure_ok, row_sums_ok


