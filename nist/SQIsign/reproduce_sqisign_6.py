def odd_primes(limit):
    flags = bytearray([1]) * (limit + 1)
    primes = []
    for q in range(3, limit + 1, 2):
        if flags[q]:
            primes.append(q)
            flags[q * q::2 * q] = bytearray(len(range(q * q, limit + 1, 2 * q)))
    return primes


def degree_weights(limit):
    """sigma(n) and psi(n) for odd n <= limit; index k holds n = 2k + 1.

    Also returns a squarefree flag computed separately from the weights.
    """
    half = (limit + 1) // 2
    small = odd_primes(isqrt(limit))
    least = array("L", [0]) * half          # least prime factor, 0 if prime
    squarefree = bytearray([1]) * half
    for q in reversed(small):
        start = (q * q - 1) // 2
        least[start::q] = array("L", [q]) * len(range(start, half, q))
        squarefree[start::q * q] = bytearray(len(range(start, half, q * q)))
    sigma = array("q", [1]) * half
    psi = array("q", [1]) * half
    for k in range(1, half):
        n = 2 * k + 1
        q = least[k] or n
        rest = n // q
        power = q                           # q^e exactly dividing n
        while rest % q == 0:
            rest //= q
            power *= q
        psi[k] = psi[rest >> 1] * (power + power // q)
        sigma[k] = sigma[rest >> 1] * ((power * q - 1) // (q - 1))
    return sigma, psi, squarefree


def hint_counts(p_unif, p_sim):
    """Hints for a z-sigma test on the count of hints with 9 | d."""
    unit = p_unif * (1 - p_unif) / (p_sim - p_unif) ** 2
    return {
        "hints_3_sigma": 9 * unit,
        "log2_hints_3_sigma": math.log2(9 * unit),
        "hints_8_sigma": 64 * unit,
        "log2_hints_8_sigma": math.log2(64 * unit),
    }


def hellinger_hints(one_minus_bc):
    """Least k with 1 - BC^k >= 1/2; TV of k samples is at least 1 - BC^k."""
    return math.ceil(math.log(2) / -math.log1p(-one_minus_bc))


def model_at_bound(sigma, psi, bound):
    half = (bound + 1) // 2                 # odd n <= bound
    s, w = sigma[:half], psi[:half]
    total_s, total_w = sum(s), sum(w)
    tv = Fraction(
        sum(abs(a * total_s - b * total_w) for a, b in zip(w, s)),
        2 * total_s * total_w,
    )
    # n = 9, 27, 45, ... are the indices 4, 13, 22, ...
    p_unif = Fraction(sum(w[4::9]), total_w)
    p_sim = Fraction(sum(s[4::9]), total_s)
    root_s, root_w = math.sqrt(total_s), math.sqrt(total_w)
    one_minus_bc = math.fsum(
        (math.sqrt(a) / root_w - math.sqrt(b) / root_s) ** 2
        for a, b in zip(w, s)
    ) / 2
    row = {
        "odd_n_below": bound,
        "tv": float(tv),
        "pr_9_divides_d_hsim_sigma": float(p_sim),
        "pr_9_divides_d_hunif_psi": float(p_unif),
        "sum_sigma_over_sum_psi": total_s / total_w,
        "one_minus_bhattacharyya": one_minus_bc,
        "hints_hellinger_tv_half": hellinger_hints(one_minus_bc),
    }
    row.update(hint_counts(float(p_unif), float(p_sim)))
    return row


def squarefree_control(sigma, psi, squarefree, bound):
    """The two weights agree exactly on squarefree n and nowhere else."""
    half = (bound + 1) // 2
    same_set = all(
        (sigma[k] == psi[k]) == bool(squarefree[k]) for k in range(half)
    )
    total_s, total_w = sum(sigma[:half]), sum(psi[:half])
    free_s = sum(sigma[k] for k in range(half) if squarefree[k])
    free_w = sum(psi[k] for k in range(half) if squarefree[k])
    # Conditional laws on squarefree n: same weights, same normalisation.
    tv_given_squarefree = Fraction(
        sum(abs(psi[k] * free_s - sigma[k] * free_w)
            for k in range(half) if squarefree[k]),
        2 * free_s * free_w,
    )
    return same_set, {
        "odd_n_below": bound,
        "tv_given_d_squarefree": float(tv_given_squarefree),
        "pr_d_squarefree_hsim_sigma": free_s / total_s,
        "pr_d_squarefree_hunif_psi": free_w / total_w,
    }


def limits(prime_cut=23):
    """Limits of the two laws as the bound grows (derived here, not in the review).

    With weight f(n) of order n on odd n <= N, the exponents v_q(n) at the
    odd primes q become independent as N grows, with
        Pr[v_q = e] = f(q^e) q^(-2e) / Z(q),
        Z_psi(q) = (q^2 + 1) / (q (q - 1)),
        Z_sigma(q) = q^3 / ((q^2 - 1)(q - 1)).
    The likelihood ratio sigma-law/psi-law is X / G, where X is the product
    of g(q^e) = sigma(q^e) / psi(q^e) and G = prod Z_sigma / Z_psi
    = prod 1 / (1 - q^-4) = pi^4 / 96.  Then
        TV = E_psi[(1 - X / G)^+],   BC = prod_q sum_e sqrt(Pr_psi Pr_sigma).
    TV is bracketed: exponents at primes <= prime_cut are enumerated; the
    remaining factor X' of X lies in [1, U] and has mean G / G_cut.
    """
    big_g = math.pi ** 4 / 96

    def pr_psi(q, e):
        weight = 1.0 if e == 0 else (q + 1) / q ** (e + 1)
        return weight * q * (q - 1) / (q * q + 1)

    def pr_sigma(q, e):
        weight = (q ** (e + 1) - 1) / ((q - 1) * q ** (2 * e))
        return weight * (q * q - 1) * (q - 1) / q ** 3

    def ratio(q, e):
        return (q ** (e + 1) - 1) / ((q * q - 1) * q ** (e - 1))

    primes = odd_primes(prime_cut)
    g_cut = 1.0                              # prod over q <= cut of 1/(1-q^-4)
    upper = math.pi ** 2 / 8                 # sup X' = prod_{q > cut} q^2/(q^2-1)
    for q in primes:
        g_cut /= 1 - q ** -4.0
        upper *= 1 - q ** -2.0
    state = {"low": 0.0, "high": 0.0, "tail": 0.0}

    def walk(index, prob, x):
        if x >= big_g:
            return                           # likelihood ratio >= 1: no term
        if index == len(primes):
            mean_term = max(0.0, 1 - x / g_cut)      # Jensen lower bound
            state["low"] += prob * mean_term
            state["high"] += prob * (
                mean_term if x * upper <= big_g else 1 - x / big_g
            )
            return
        q = primes[index]
        walk(index + 1, prob * (pr_psi(q, 0) + pr_psi(q, 1)), x)
        e = 2
        while q ** e < 2 ** 64:
            g = ratio(q, e)
            if x * g >= big_g:
                break                        # g(q^e) grows with e
            walk(index + 1, prob * pr_psi(q, e), x * g)
            e += 1
        else:
            state["tail"] += prob * pr_psi(q, e) * q / (q - 1)

    walk(0, 1.0, 1.0)
    tv_low = state["low"]
    tv_high = state["high"] + state["tail"] * (1 - 1 / big_g)

    minus_log_bc = 0.0                       # tail beyond q = 1000 is < 1e-15
    for q in odd_primes(1000):
        distance, e = 0.0, 0
        while True:
            a, b = pr_psi(q, e), pr_sigma(q, e)
            distance += (math.sqrt(a) - math.sqrt(b)) ** 2
            if a < 1e-40:
                break
            e += 1
        minus_log_bc -= math.log1p(-distance / 2)
    one_minus_bc = -math.expm1(-minus_log_bc)

    # v_3 >= 2: 1 - Pr[v_3 = 0] - Pr[v_3 = 1], exactly.
    p_unif = 1 - Fraction(3 * 2, 10) * (1 + Fraction(4, 9))
    p_sim = 1 - Fraction(8 * 2, 27) * (1 + Fraction(4, 9))
    row = {
        "tv_lower": tv_low,
        "tv_upper": tv_high,
        "tv_bracket_enumerates_primes_up_to": prime_cut,
        "pr_9_divides_d_hsim_sigma": float(p_sim),
        "pr_9_divides_d_hunif_psi": float(p_unif),
        "pr_9_divides_d_exact": {"hsim_sigma": str(p_sim), "hunif_psi": str(p_unif)},
        "sum_sigma_over_sum_psi": big_g,
        "one_minus_bhattacharyya": one_minus_bc,
        "hints_hellinger_tv_half": hellinger_hints(one_minus_bc),
    }
    row.update(hint_counts(float(p_unif), float(p_sim)))
    return row


