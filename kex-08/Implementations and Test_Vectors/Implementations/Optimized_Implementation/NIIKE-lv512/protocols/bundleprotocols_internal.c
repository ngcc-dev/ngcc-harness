void encode_bundlevertex(void *dst, const bundlevertex_t *in)
{
    fp2_t invlist[5*CYCLE_LENGTH];
    for (int i = 0; i < CYCLE_LENGTH; i++)
    {
        fp2_copy(&(invlist[5*i]), &(in->A24.z.list[i]));
        fp2_copy(&(invlist[5*i + 1]), &(in->Ps.z.list[i]));
        fp2_copy(&(invlist[5*i + 2]), &(in->Pt.z.list[i]));
        fp2_copy(&(invlist[5*i + 3]), &(in->Qs.z.list[i]));
        fp2_copy(&(invlist[5*i + 4]), &(in->Qt.z.list[i]));
    }
    fp2_batched_inv(invlist, 5*CYCLE_LENGTH);
    fp2_t result;
    for (int i = 0; i < CYCLE_LENGTH; i++)
    {
        fp2_mul(&result, &(in->A24.x.list[i]), &(invlist[5*i]));
        fp2_encode(dst+ 5 * i * FP2_ENCODED_BYTES, &result);
        fp2_mul(&result, &(in->Ps.x.list[i]), &(invlist[5*i + 1]));
        fp2_encode(dst+ (5*i + 1) * FP2_ENCODED_BYTES, &result);
        fp2_mul(&result, &(in->Pt.x.list[i]), &(invlist[5*i + 2]));
        fp2_encode(dst+ (5*i + 2) * FP2_ENCODED_BYTES, &result);
        fp2_mul(&result, &(in->Qs.x.list[i]), &(invlist[5*i + 3]));
        fp2_encode(dst+ (5*i + 3) * FP2_ENCODED_BYTES, &result);
        fp2_mul(&result, &(in->Qt.x.list[i]), &(invlist[5*i + 4]));
        fp2_encode(dst+ (5*i + 4) * FP2_ENCODED_BYTES, &result);
    }
}

void decode_bundlevertex(bundlevertex_t *out, void *in)
{
    for (int i = 0; i < CYCLE_LENGTH; i++)
    {
        fp2_decode(&(out->A24.x.list[i]), in + 5 * i * FP2_ENCODED_BYTES);
        fp2_setone(&(out->A24.z.list[i]));
        fp2_decode(&(out->Ps.x.list[i]), in + (5*i + 1) * FP2_ENCODED_BYTES);
        fp2_setone(&(out->Ps.z.list[i]));
        fp2_decode(&(out->Pt.x.list[i]), in + (5*i + 2) * FP2_ENCODED_BYTES);
        fp2_setone(&(out->Pt.z.list[i]));
        fp2_decode(&(out->Qs.x.list[i]), in + (5*i + 3) * FP2_ENCODED_BYTES);
        fp2_setone(&(out->Qs.z.list[i]));
        fp2_decode(&(out->Qt.x.list[i]), in + (5*i + 4) * FP2_ENCODED_BYTES);
        fp2_setone(&(out->Qt.z.list[i]));
    }
}

