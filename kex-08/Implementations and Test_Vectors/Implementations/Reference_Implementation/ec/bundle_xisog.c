// Degree-2 isogeny with kernel generated by P != (0 ,0)
// Outputs the curve coefficient in the form A24=(A+2C:4C)
void bundlexisog_2(bundleec_point_t* B, bundleec_point_t const P, int len)
{
	// for (int i = 0; i < len; i++)
	// {
	// 	assert(!fp2_is_zero(&(P.x.list[i])));
	// }
    bundlefp2_sqr(&B->x, &P.x, len);
    bundlefp2_sqr(&B->z, &P.z, len);
    bundlefp2_sub(&B->x, &B->z, &B->x, len);
	// fp2_print(B->x.list[len-1]);
	// printf("\n");
	// fp2_print(B->z.list[len-1]);
	// fflush(stdout);
    bundlefp2_add(&bundleK[0].x, &P.x, &P.z, len);
    bundlefp2_sub(&bundleK[0].z, &P.x, &P.z, len);
}

void bundlexisog_2_singular(bundleec_point_t *B24, bundleec_point_t A24, int len)
{
    // No need to check the square root, only used for signing.
    bundlefp2_t t0, four, invA24z;
    bundlefp2_set(&four, 4, len);
    bundlefp2_add(&t0, &A24.x, &A24.x, len);
    bundlefp2_sub(&t0, &t0, &A24.z, len);
    bundlefp2_add(&t0, &t0, &t0, len);
	bundlefp2_copy(&invA24z, &A24.z, len);
    bundlefp2_inv(&invA24z, len);
    bundlefp2_mul(&t0, &t0, &invA24z, len);
    bundlefp2_copy(&bundleK[2].x, &t0, len);
    bundlefp2_add(&B24->x, &t0, &t0, len);
    bundlefp2_sqr(&t0, &t0, len);
    bundlefp2_sub(&t0, &t0, &four, len);
    bundlefp2_sqrt(&t0, len);
    bundlefp2_neg(&bundleK[2].z, &t0, len);
    bundlefp2_add(&B24->z, &t0, &t0, len);
    bundlefp2_add(&B24->x, &B24->x, &B24->z, len);
    bundlefp2_add(&B24->z, &B24->z, &B24->z, len);
	// fp2_print(B24->x.list[CYCLE_LENGTH-1]);
	// printf("\n");
	// fp2_print(B24->z.list[CYCLE_LENGTH-1]);
	// fflush(stdout);
}

// xISOG procedure, which is a hybrid between Montgomery and Twisted Edwards
// This tradition fomulae corresponds with the Twisted Edwards formulae but 
// mapping the output into Montgomery form
void bundlexisog_t(bundleec_point_t* B, uint64_t const i, bundleec_point_t const A, int len)
{
	if (TORSION_ODD_PRIMES[i] == 2)
	{
		bundleec_point_t res1, res2;
		bundlexisog_2(&res1, bundleK[1], len);
		bundlexisog_2_singular(&res2, A, len);
		uint32_t iszero[CYCLE_LENGTH];
		// fp2_print(bundleK[1].x.list[13]);
		// printf("\n");
		// fp2_print(bundleK[1].z.list[13]);
		// fflush(stdout);
		bundlefp2_is_zero_mask(iszero, &(bundleK[1].x), len);
		bundleec_point_select(B, &res1, &res2, iszero, len);
		return;
	}
	int j;
	int d = ((int)TORSION_ODD_PRIMES[i] - 1) / 2;	// Here, l = 2d + 1

	bundlefp2_t By, Bz, constant_d_edwards, tmp_a, tmp_d;

	bundlefp2_copy(&By, &bundleK[0].x, len);
	bundlefp2_copy(&Bz, &bundleK[0].z, len);

	for (j = 1; j < d; j++)
	{
		bundlefp2_mul(&By, &By, &bundleK[j].x, len);
		bundlefp2_mul(&Bz, &Bz, &bundleK[j].z, len);
	};

	// Mapping Montgomery curve coefficients into Twisted Edwards form
	bundlefp2_sub(&constant_d_edwards, &A.x, &A.z, len);
	bundlefp2_copy(&tmp_a, &A.x, len);
	bundlefp2_copy(&tmp_d, &constant_d_edwards, len);

	// left-to-right method for computing a^l and d^l
	for (j = 1; j < (int)p_plus_minus_bitlength[i]; j++)
	{
		bundlefp2_sqr(&tmp_a, &tmp_a, len);
		bundlefp2_sqr(&tmp_d, &tmp_d, len);
		if( ( ((int)TORSION_ODD_PRIMES[i] >> ((int)p_plus_minus_bitlength[i] - j - 1)) & 1 ) != 0 )
		{
			bundlefp2_mul(&tmp_a, &tmp_a, &A.x, len);
			bundlefp2_mul(&tmp_d, &tmp_d, &constant_d_edwards, len);
		};
	};

	// raising to 8-th power
	for (j = 0; j < 3; j++)
	{
		bundlefp2_sqr(&By, &By, len);
		bundlefp2_sqr(&Bz, &Bz, len);
	};

	// Mapping Twisted Edwards curve coefficients into Montgomery form
	bundlefp2_mul(&(B->x), &tmp_a, &Bz, len);
	bundlefp2_mul(&(B->z), &tmp_d, &By, len);
	bundlefp2_sub(&(B->z), &(B->x), &(B->z), len);
}

