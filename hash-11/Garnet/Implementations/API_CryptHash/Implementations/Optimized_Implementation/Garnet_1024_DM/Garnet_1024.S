pad_message:
    // %rdi = msg, %rsi = bit_len
    movq %rsi, %rax
    shrq $3, %rax                       // byte_num = bit_len / 8
    movq %rsi, %rcx
    andq $7, %rcx                       // bit_idx = bit_len % 8
    jz .Lpad_zero_rem

    // mask1 = ~((1 << (8 - bit_idx)) - 1)
    movq $8, %rdx
    subq %rcx, %rdx
    movq $1, %r8
    movq %rdx, %rcx
    shlq %cl, %r8
    decq %r8
    notq %r8

    // msg[byte_num] &= mask1
    movzbl (%rdi,%rax), %r9d
    andl %r8d, %r9d

    // msg[byte_num] |= 1 << (7 - bit_idx)
    movq %rsi, %rcx
    andq $7, %rcx
    movq $7, %rdx
    subq %rcx, %rdx
    movq $1, %r8
    movq %rdx, %rcx
    shlq %cl, %r8
    orl %r8d, %r9d

    // mask = ~((1 << (7 - bit_idx)) - 1)
    movq $1, %r8
    movq %rdx, %rcx
    shlq %cl, %r8
    decq %r8
    notq %r8

    // msg[byte_num] &= mask
    andl %r8d, %r9d
    movb %r9b, (%rdi,%rax)
    ret

.Lpad_zero_rem:
    movb $0x80, (%rdi,%rax)
    ret
.size pad_message, .-pad_message

