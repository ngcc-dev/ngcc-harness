// =====================================================================
// 宏定义 (Macro Definitions)
// =====================================================================

// GF(2^128) 乘以 \alpha (MC4 缩减多项式: x^128 + x^7 + x^2 + x + 1)
// 输入: \low, \high (原始的 128 位值寄存器)
// 输出: \out_low, \out_high (乘 \alpha 后的 128 位值)
// 临时寄存器: %rcx (安全地使用 %rcx 隔离状态寄存器)
.macro mul_alpha_MC4 low, high, out_low, out_high
    movq \low, \out_low
    movq \high, \out_high
    shldq $1, \out_low, \out_high   // 高 64 位左移并移入低 64 位的最高位
    shlq $1, \out_low               // 低 64 位左移
    movq \high, %rcx
    sarq $63, %rcx                  // 提取 MSB 构成掩码（若 MSB 为 1，则为全 1）
    andq $0x87, %rcx                // 缩减常量 0x87
    xorq %rcx, \out_low             // 条件异或
.endm

// GF(2^128) 乘以 \alpha (MD4 缩减多项式: x^128 + x^29 + x^15 + x^2 + 1)
// 输入: \low, \high
// 输出: \out_low, \out_high
// 临时寄存器: %rcx
.macro mul_alpha_MD4 low, high, out_low, out_high
    movq \low, \out_low
    movq \high, \out_high
    shldq $1, \out_low, \out_high
    shlq $1, \out_low
    movq \high, %rcx
    sarq $63, %rcx
    andq $0x20008005, %rcx          // 缩减常量 0x20008005
    xorq %rcx, \out_low
.endm

// 用于 MixDiagonal 的辅助宏，处理一组 4x4 状态中的对角线混淆
.macro mix_diag_grp base, off0, off1, off2, off3
    // 加载 s0..s3 状态 (每个状态占用 16 字节)
    movq \off0(\base), %r8
    movq \off0+8(\base), %r9
    movq \off1(\base), %r10
    movq \off1+8(\base), %r11
    movq \off2(\base), %r12
    movq \off2+8(\base), %r13
    movq \off3(\base), %r14
    movq \off3+8(\base), %r15

    // 计算 as0 并存入栈 (0(%rsp))
    mul_alpha_MD4 %r8, %r9, %rbx, %rdx
    movq %rbx, 0(%rsp)
    movq %rdx, 8(%rsp)

    // 计算 as1 并存入栈 (16(%rsp))
    mul_alpha_MD4 %r10, %r11, %rbx, %rdx
    movq %rbx, 16(%rsp)
    movq %rdx, 24(%rsp)

    // 计算 as2 并存入栈 (32(%rsp))
    mul_alpha_MD4 %r12, %r13, %rbx, %rdx
    movq %rbx, 32(%rsp)
    movq %rdx, 40(%rsp)

    // 计算 as3 并存入栈 (48(%rsp))
    mul_alpha_MD4 %r14, %r15, %rbx, %rdx
    movq %rbx, 48(%rsp)
    movq %rdx, 56(%rsp)

    // 计算 t0 = as0 ^ as1 ^ s1 ^ s2 ^ s3 并写回
    movq 0(%rsp), %rbx
    movq 8(%rsp), %rdx
    xorq 16(%rsp), %rbx
    xorq 24(%rsp), %rdx
    xorq %r10, %rbx
    xorq %r11, %rdx
    xorq %r12, %rbx
    xorq %r13, %rdx
    xorq %r14, %rbx
    xorq %r15, %rdx
    movq %rbx, \off0(\base)
    movq %rdx, \off0+8(\base)

    // 计算 t1 = s0 ^ as1 ^ as2 ^ s2 ^ s3 并写回
    movq %r8, %rbx
    movq %r9, %rdx
    xorq 16(%rsp), %rbx
    xorq 24(%rsp), %rdx
    xorq 32(%rsp), %rbx
    xorq 40(%rsp), %rdx
    xorq %r12, %rbx
    xorq %r13, %rdx
    xorq %r14, %rbx
    xorq %r15, %rdx
    movq %rbx, \off1(\base)
    movq %rdx, \off1+8(\base)

    // 计算 t2 = s0 ^ s1 ^ as2 ^ as3 ^ s3 并写回
    movq %r8, %rbx
    movq %r9, %rdx
    xorq %r10, %rbx
    xorq %r11, %rdx
    xorq 32(%rsp), %rbx
    xorq 40(%rsp), %rdx
    xorq 48(%rsp), %rbx
    xorq 56(%rsp), %rdx
    xorq %r14, %rbx
    xorq %r15, %rdx
    movq %rbx, \off2(\base)
    movq %rdx, \off2+8(\base)

    // 计算 t3 = as0 ^ s0 ^ s1 ^ s2 ^ as3 并写回
    movq 0(%rsp), %rbx
    movq 8(%rsp), %rdx
    xorq %r8, %rbx
    xorq %r9, %rdx
    xorq %r10, %rbx
    xorq %r11, %rdx
    xorq %r12, %rbx
    xorq %r13, %rdx
    xorq 48(%rsp), %rbx
    xorq 56(%rsp), %rdx
    movq %rbx, \off3(\base)
    movq %rdx, \off3+8(\base)
.endm


