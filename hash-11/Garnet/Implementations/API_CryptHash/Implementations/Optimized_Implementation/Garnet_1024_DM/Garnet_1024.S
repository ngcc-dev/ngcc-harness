.align 16
.global subword_4x4_st
.type subword_4x4_st, @function
subword_4x4_st:
    // %rdi = state, %rsi = key.v[0], %rdx = key.v[1]
    pushq %rbx
    pushq %r12
    pushq %r13
    subq $32, %rsp                      // 0(%rsp) 留给 out, 16(%rsp) 存放 round_key

    movq %rdi, %r12                     // %r12 = state
    movq %rsi, 16(%rsp)                 // 存 round_key
    movq %rdx, 24(%rsp)

    movq $0, %r13                       // 循环变量 i = 0..15

.Lsubword_loop:
    // 计算偏移：%rax = i * 16 (规避 x86-64 比例因子寻址限制)
    movq %r13, %rax
    shlq $4, %rax

    movq %rsp, %rdi                     // %rdi = out 的地址
    leaq (%r12,%rax), %rsi              // %rsi = in (state + i * 16)
    leaq 16(%rsp), %rdx                 // %rdx = rk 的地址
    call aesround

    // 计算写回偏移：%rax = i * 16
    movq %r13, %rax
    shlq $4, %rax
    leaq (%r12,%rax), %rdi              // %rdi = state + i * 16

    // 将 aesround 输出写回 state[i]
    movq 0(%rsp), %rax
    movq 8(%rsp), %rcx
    movq %rax, 0(%rdi)
    movq %rcx, 8(%rdi)

    incq %r13
    cmpq $16, %r13
    jne .Lsubword_loop

    addq $32, %rsp
    popq %r13
    popq %r12
    popq %rbx
    ret
.size subword_4x4_st, .-subword_4x4_st

.align 16
.global add_constant_4x4_st
.type add_constant_4x4_st, @function
add_constant_4x4_st:
    // %rdi = state, %rsi = round (整型)
    // 显式带符号扩展，消除高 32 位可能的垃圾数据
    movslq %esi, %rsi                   
    // 斐波那契常量数组每行 24 字节。 计算偏移: round * 24
    leaq (%rsi,%rsi,2), %rax            // rax = round * 3
    shlq $3, %rax                       // rax = round * 24

    leaq Fibonacci_4x4(%rip), %rcx
    movq 0(%rcx,%rax), %rdx             // c0
    movq 8(%rcx,%rax), %r8              // c1
    movq 16(%rcx,%rax), %r9             // c2

    xorq %rdx, 112(%rdi)                // state[7].v[0] ^= c0
    xorq %r8, 176(%rdi)                 // state[11].v[0] ^= c1
    xorq %r9, 240(%rdi)                 // state[15].v[0] ^= c2
    ret
.size add_constant_4x4_st, .-add_constant_4x4_st

.align 16
.global permutation_p_4x4_st
.type permutation_p_4x4_st, @function
permutation_p_4x4_st:
    // %rdi = state, %rsi = key.v[0], %rdx = key.v[1], %rcx = round
    pushq %r12
    pushq %r13
    movq %rdi, %r12
    movq %rcx, %r13

    // 1. subword
    call subword_4x4_st

    // 2. mix column
