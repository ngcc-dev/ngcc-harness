    jz .Lpad2_zero_rem

    // msg[byte_num] |= 1 << (7 - bit_idx)
    movq $7, %rdx
    subq %rcx, %rdx
    movq $1, %r8
    movq %rdx, %rcx
    shlq %cl, %r8
    movzbl (%rdi,%rax), %r9d
    orl %r8d, %r9d

    // mask = ~((1 << (7 - bit_idx)) - 1)
    movq $1, %r8
    movq %rdx, %rcx
    shlq %cl, %r8
    decq %r8
    notq %r8

    // msg[byte_num] &= mask
    andl %r8d, %r9d
    movb %r9b, (%rdi,%rax)
    ret

.Lpad2_zero_rem:
    movb $0x80, (%rdi,%rax)
