.align 16
.global garnet_1024
.type garnet_1024, @function
garnet_1024:
    // %rdi = message, %rsi = mlength, %rdx = digest, %rcx = state
    pushq %rbx
    pushq %r12
    pushq %r13
    pushq %r14
    pushq %r15
    // 栈上保留 304 字节: 
    // 0(%rsp)..111(%rsp)   = msg (112 字节, 7 个 128 位)
    // 112(%rsp)..255(%rsp) = cap (144 字节, 9 个 128 位)
    // 256(%rsp)..271(%rsp) = lastblock (16 字节)
    // 272(%rsp)            = message 备份 (8 字节)
    // 280(%rsp)            = byte_num 备份 (8 字节)
    // 288(%rsp)            = digest 备份 (8 字节)
    // 296(%rsp)            = state 备份 (8 字节)
    subq $304, %rsp

    // 初始化状态 IV 并将其拷贝至目标 state 寄存器 (%rcx)
    leaq Garnet_IV(%rip), %rax
    movdqu 0(%rax), %xmm0
    movdqu %xmm0, 0(%rcx)
    movdqu 16(%rax), %xmm0
    movdqu %xmm0, 16(%rcx)
    movdqu 32(%rax), %xmm0
    movdqu %xmm0, 32(%rcx)
    movdqu 48(%rax), %xmm0
    movdqu %xmm0, 48(%rcx)
    movdqu 64(%rax), %xmm0
    movdqu %xmm0, 64(%rcx)
    movdqu 80(%rax), %xmm0
    movdqu %xmm0, 80(%rcx)
    movdqu 96(%rax), %xmm0
    movdqu %xmm0, 96(%rcx)
    movdqu 112(%rax), %xmm0
    movdqu %xmm0, 112(%rcx)
    movdqu 128(%rax), %xmm0
    movdqu %xmm0, 128(%rcx)
    movdqu 144(%rax), %xmm0
    movdqu %xmm0, 144(%rcx)
    movdqu 160(%rax), %xmm0
    movdqu %xmm0, 160(%rcx)
    movdqu 176(%rax), %xmm0
    movdqu %xmm0, 176(%rcx)
    movdqu 192(%rax), %xmm0
    movdqu %xmm0, 192(%rcx)
    movdqu 208(%rax), %xmm0
    movdqu %xmm0, 208(%rcx)
    movdqu 224(%rax), %xmm0
    movdqu %xmm0, 224(%rcx)
    movdqu 240(%rax), %xmm0
    movdqu %xmm0, 240(%rcx)

    // 备份常用寄存器参数至栈
    movq %rdi, 272(%rsp)
    movq %rsi, %r12                     // r12 = mlength
    movq %rdx, 288(%rsp)
    movq %rcx, 296(%rsp)

    // 计算 byte_num = (mlength + 7) >> 3
    leaq 7(%rsi), %rax
    shrq $3, %rax
    movq %rax, 280(%rsp)                 // 保存 byte_num

    // 吸收循环初始化 i = 0 (用 r13 存储)
    movq $0, %r13

.Labsorb_loop:
    movq 280(%rsp), %rax                 // 检查 (i + 112) <= byte_num
    leaq 112(%r13), %rcx
    cmpq %rax, %rcx
    jg .Labsorb_loop_end

    // 拷贝 112 字节数据至栈中的临时 msg 缓冲区 0(%rsp)
    movq 272(%rsp), %rsi
    addq %r13, %rsi
    movq %rsp, %rdi
    movdqu 0(%rsi), %xmm0
    movdqu %xmm0, 0(%rdi)
    movdqu 16(%rsi), %xmm0
    movdqu %xmm0, 16(%rdi)
    movdqu 32(%rsi), %xmm0
    movdqu %xmm0, 32(%rdi)
    movdqu 48(%rsi), %xmm0
    movdqu %xmm0, 48(%rdi)
    movdqu 64(%rsi), %xmm0
    movdqu %xmm0, 64(%rdi)
    movdqu 80(%rsi), %xmm0
    movdqu %xmm0, 80(%rdi)
    movdqu 96(%rsi), %xmm0
    movdqu %xmm0, 96(%rdi)

    // keep_capacity5_4x4_st(state, cap)
    movq 296(%rsp), %rdi
    leaq 112(%rsp), %rsi
    call keep_capacity5_4x4_st

    // absorb_message5_4x4_st(state, msg)
    movq 296(%rsp), %rdi
    movq %rsp, %rsi
    call absorb_message5_4x4_st

    // 12 轮 P 变换
    movq $0, %r14                       // j = 0
.Lj_loop1:
    movq 296(%rsp), %rdi
    movq $0, %rsi                       // zero_key.v[0] = 0
    movq $0, %rdx                       // zero_key.v[1] = 0
    movq %r14, %rcx                     // round_id = j
    call permutation_p_4x4_st
    incq %r14
    cmpq $12, %r14
    jne .Lj_loop1

    //// absorb_message5_4x4_st(state, msg)
    movq 296(%rsp), %rdi
    movq %rsp, %rsi
    call absorb_message5_4x4_st

    // absorb_capacity5_4x4_st(state, cap)
    movq 296(%rsp), %rdi
    leaq 112(%rsp), %rsi
    call absorb_capacity5_4x4_st

    addq $112, %r13                      // i += 112
    jmp .Labsorb_loop

.Labsorb_loop_end:
    // 处理部分块
    movq $0, %r15                       // j = 0 (使用 r15 寄存器)

.Lpartial_loop:
    movq 280(%rsp), %rax
    leaq 16(%r13), %rcx
    cmpq %rax, %rcx
    jg .Lpartial_loop_end

    // memcpy(lastblock, message + i, 16)
    movq 272(%rsp), %rsi
    addq %r13, %rsi
    movq 0(%rsi), %rax
    movq 8(%rsi), %rcx
    movq %rax, 256(%rsp)
    movq %rcx, 264(%rsp)

    // memcpy(&msg[j], lastblock, 16)
    movq %r15, %rdx
    shlq $4, %rdx                       // j * 16
    leaq 0(%rsp,%rdx), %rdi
    movq %rax, 0(%rdi)
    movq %rcx, 8(%rdi)

    incq %r15
    addq $16, %r13
    jmp .Lpartial_loop

.Lpartial_loop_end:
    // 检查尾部部分块
    movq 280(%rsp), %rax
    movq %rax, %rcx
    andq $15, %rcx                      // byte_num & 0xf
    jz .Lelse_if_padding

    // if ((byte_num & 0xf) != 0)
    // memset(lastblock, 0, 16)
    movq $0, 256(%rsp)
    movq $0, 264(%rsp)

    // memcpy(lastblock, message + i, (byte_num & 0xf) + 1)
    incq %rcx
    movq %rcx, %rdx                     // 第 3 参数: 长度 n
    movq 272(%rsp), %rsi
    addq %r13, %rsi                     // 第 2 参数: src
    leaq 256(%rsp), %rdi                 // 第 1 参数: dest
    call memcpy

    // memcpy(&msg[j], lastblock, 16)
    movq %r15, %rdx
    shlq $4, %rdx
    leaq 0(%rsp,%rdx), %rdi
    movq 256(%rsp), %rax
    movq 264(%rsp), %rcx
    movq %rax, 0(%rdi)
    movq %rcx, 8(%rdi)
    jmp .Lpadding_done

.Lelse_if_padding:
    // else if ((mlength % 8) == 0)
    movq %r12, %rax
    andq $7, %rax
    jnz .Lelse_padding

    // memset(lastblock, 0, 16); lastblock[0] = 0x80;
    movq $0, 256(%rsp)
    movq $0, 264(%rsp)
    movb $0x80, 256(%rsp)

    // memcpy(&msg[j], lastblock, 16)
    movq %r15, %rdx
    shlq $4, %rdx
    leaq 0(%rsp,%rdx), %rdi
    movq 256(%rsp), %rax
    movq 264(%rsp), %rcx
    movq %rax, 0(%rdi)
    movq %rcx, 8(%rdi)
    jmp .Lpadding_done

.Lelse_padding:
    // else: zero128(msg + j)
    movq %r15, %rdx
    shlq $4, %rdx
    leaq 0(%rsp,%rdx), %rdi
    call zero128

.Lpadding_done:
    // 填充多余块
    incq %r15

.Lwhile_j_loop:
    cmpq $7, %r15
    jge .Lwhile_j_loop_end
    movq %r15, %rdx
    shlq $4, %rdx
    leaq 0(%rsp,%rdx), %rdi
    call zero128
    incq %r15
    jmp .Lwhile_j_loop

.Lwhile_j_loop_end:
    // keep_capacity5_4x4_st(state, cap)
    movq 296(%rsp), %rdi
    leaq 112(%rsp), %rsi
    call keep_capacity5_4x4_st

    // 调用 absorb_message5_4x4_st(state, msg) 并再进行 12 轮变换
    movq 296(%rsp), %rdi
    movq %rsp, %rsi
    call absorb_message5_4x4_st

    movq $0, %r14
.Lj_loop2:
    movq 296(%rsp), %rdi
    movq $0, %rsi
    movq $0, %rdx
    movq %r14, %rcx
    call permutation_p_4x4_st
    incq %r14
    cmpq $12, %r14
    jne .Lj_loop2

    // absorb_message5_4x4_st(state, msg) (Sponge-DM)
    movq 296(%rsp), %rdi
    movq %rsp, %rsi
    call absorb_message5_4x4_st

    // absorb_capacity5_4x4_st(state, cap)
    movq 296(%rsp), %rdi
    leaq 112(%rsp), %rsi
    call absorb_capacity5_4x4_st

    // 吸收消息长度：absorb_message_4x4_st(state, msglen)
    movq 296(%rsp), %rdi
    movq %r12, %rsi                     // msglen.v[0] = mlength
    movq $0, %rdx                       // msglen.v[1] = 0
    call absorb_message_4x4_st

    // 1. 中间处理阶段 (16 轮, 密钥常数：one_key = {7, 0})
    movq $0, %r13
.Li_loop1:
    movq 296(%rsp), %rdi
    movq $7, %rsi
    movq $0, %rdx
    movq %r13, %rcx
    call permutation_p_4x4_st
    incq %r13
    cmpq $16, %r13
    jne .Li_loop1

    // 2. 挤出摘要阶段 (12 轮, 密钥常数：two_key = {8, 0})
    movq $0, %r13
.Li_loop2:
    movq 296(%rsp), %rdi
    movq $8, %rsi
    movq $0, %rdx
    movq %r13, %rcx
    call permutation_p_4x4_st
    incq %r13
    cmpq $12, %r13
    jne .Li_loop2

    // 提取 1024 字节的摘要
    movq 296(%rsp), %rax                 // %rax = state pointer
    movq 288(%rsp), %rdx                 // %rdx = digest pointer

    movups 0(%rax), %xmm0
    movups %xmm0, 0(%rdx)

    movups 32(%rax), %xmm0
    movups %xmm0, 16(%rdx)

    movups 80(%rax), %xmm0
    movups %xmm0, 32(%rdx)

    movups 112(%rax), %xmm0
    movups %xmm0, 48(%rdx)

    movups 144(%rax), %xmm0
    movups %xmm0, 64(%rdx)

    movups 176(%rax), %xmm0
    movups %xmm0, 80(%rdx)

    movups 192(%rax), %xmm0
    movups %xmm0, 96(%rdx)

    movups 224(%rax), %xmm0
    movups %xmm0, 112(%rdx)

    // 释放栈空间，恢复被保护的寄存器
    addq $304, %rsp
    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %rbx
    ret
.size garnet_1024, .-garnet_1024


