.align 16
.global aesround
.type aesround, @function
aesround:
    // %rdi = out, %rsi = in, %rdx = rk
    // 采用位置无关码 (PIC) 兼容的方式查找 T-table 字节

    // --- Word 0 ---
    movzbl 0(%rsi), %eax
    movzbl 5(%rsi), %ecx
    movzbl 10(%rsi), %r8d
    movzbl 15(%rsi), %r9d
    leaq TE0(%rip), %r11
    movl (%r11,%rax,4), %r10d
    leaq TE1(%rip), %r11
    xorl (%r11,%rcx,4), %r10d
    leaq TE2(%rip), %r11
    xorl (%r11,%r8,4), %r10d
    leaq TE3(%rip), %r11
    xorl (%r11,%r9,4), %r10d
    xorl 0(%rdx), %r10d
    movl %r10d, 0(%rdi)

    // --- Word 1 ---
    movzbl 4(%rsi), %eax
    movzbl 9(%rsi), %ecx
    movzbl 14(%rsi), %r8d
    movzbl 3(%rsi), %r9d
    leaq TE0(%rip), %r11
    movl (%r11,%rax,4), %r10d
    leaq TE1(%rip), %r11
    xorl (%r11,%rcx,4), %r10d
    leaq TE2(%rip), %r11
    xorl (%r11,%r8,4), %r10d
    leaq TE3(%rip), %r11
    xorl (%r11,%r9,4), %r10d
    xorl 4(%rdx), %r10d
    movl %r10d, 4(%rdi)

    // --- Word 2 ---
    movzbl 8(%rsi), %eax
    movzbl 13(%rsi), %ecx
    movzbl 2(%rsi), %r8d
    movzbl 7(%rsi), %r9d
    leaq TE0(%rip), %r11
    movl (%r11,%rax,4), %r10d
    leaq TE1(%rip), %r11
    xorl (%r11,%rcx,4), %r10d
    leaq TE2(%rip), %r11
    xorl (%r11,%r8,4), %r10d
    leaq TE3(%rip), %r11
    xorl (%r11,%r9,4), %r10d
    xorl 8(%rdx), %r10d
    movl %r10d, 8(%rdi)

    // --- Word 3 ---
    movzbl 12(%rsi), %eax
    movzbl 1(%rsi), %ecx
    movzbl 6(%rsi), %r8d
    movzbl 11(%rsi), %r9d
    leaq TE0(%rip), %r11
    movl (%r11,%rax,4), %r10d
    leaq TE1(%rip), %r11
    xorl (%r11,%rcx,4), %r10d
    leaq TE2(%rip), %r11
    xorl (%r11,%r8,4), %r10d
    leaq TE3(%rip), %r11
    xorl (%r11,%r9,4), %r10d
    xorl 12(%rdx), %r10d
    movl %r10d, 12(%rdi)
    ret
.size aesround, .-aesround

.align 16
.global mix_column_4x4_st
.type mix_column_4x4_st, @function
mix_column_4x4_st:
    // %rdi = state
    pushq %rbx
    pushq %rbp
    pushq %r12
    pushq %r13
    pushq %r14
    pushq %r15
    subq $64, %rsp                      // 在栈上开辟 64 字节存放 as0..as3

    movq %rdi, %rax                     // %rax = base address
    movq $4, %rsi                       // col 循环计数器 (4 次)

.Lloop_mc:
    // 加载当前列的 4 个 128 位状态
    movq 0(%rax), %r8
    movq 8(%rax), %r9
    movq 64(%rax), %r10
    movq 72(%rax), %r11
    movq 128(%rax), %r12
    movq 136(%rax), %r13
    movq 192(%rax), %r14
    movq 200(%rax), %r15

    // 依次乘 MC4 常数并存入栈中
    mul_alpha_MC4 %r8, %r9, %rbx, %rdx
    movq %rbx, 0(%rsp)
    movq %rdx, 8(%rsp)

    mul_alpha_MC4 %r10, %r11, %rbx, %rdx
    movq %rbx, 16(%rsp)
    movq %rdx, 24(%rsp)

    mul_alpha_MC4 %r12, %r13, %rbx, %rdx
    movq %rbx, 32(%rsp)
    movq %rdx, 40(%rsp)

    mul_alpha_MC4 %r14, %r15, %rbx, %rdx
    movq %rbx, 48(%rsp)
    movq %rdx, 56(%rsp)

    // 计算 t0 并写回 state[ind0]
    movq 0(%rsp), %rbx
    movq 8(%rsp), %rdx
    xorq 16(%rsp), %rbx
    xorq 24(%rsp), %rdx
    xorq %r10, %rbx
    xorq %r11, %rdx
    xorq %r12, %rbx
    xorq %r13, %rdx
    xorq %r14, %rbx
    xorq %r15, %rdx
    movq %rbx, 0(%rax)
    movq %rdx, 8(%rax)

    // 计算 t1 并写回 state[ind1]
    movq %r8, %rbx
    movq %r9, %rdx
    xorq 16(%rsp), %rbx
    xorq 24(%rsp), %rdx
    xorq 32(%rsp), %rbx
    xorq 40(%rsp), %rdx
    xorq %r12, %rbx
    xorq %r13, %rdx
    xorq %r14, %rbx
    xorq %r15, %rdx
    movq %rbx, 64(%rax)
    movq %rdx, 72(%rax)

    // 计算 t2 并写回 state[ind2]
    movq %r8, %rbx
    movq %r9, %rdx
    xorq %r10, %rbx
    xorq %r11, %rdx
    xorq 32(%rsp), %rbx
    xorq 40(%rsp), %rdx
    xorq 48(%rsp), %rbx
    xorq 56(%rsp), %rdx
    xorq %r14, %rbx
    xorq %r15, %rdx
    movq %rbx, 128(%rax)
    movq %rdx, 136(%rax)

    // 计算 t3 并写回 state[ind3]
    movq 0(%rsp), %rbx
    movq 8(%rsp), %rdx
    xorq %r8, %rbx
    xorq %r9, %rdx
    xorq %r10, %rbx
    xorq %r11, %rdx
    xorq %r12, %rbx
    xorq %r13, %rdx
    xorq 48(%rsp), %rbx
    xorq 56(%rsp), %rdx
    movq %rbx, 192(%rax)
    movq %rdx, 200(%rax)

    addq $16, %rax                      // 下一列
    decq %rsi
    jnz .Lloop_mc

    addq $64, %rsp
    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %rbp
    popq %rbx
    ret
.size mix_column_4x4_st, .-mix_column_4x4_st

.align 16
.global mix_diagonal_4x4_st
.type mix_diagonal_4x4_st, @function
mix_diagonal_4x4_st:
    // %rdi = state
    pushq %rbx
    pushq %rbp
    pushq %r12
    pushq %r13
    pushq %r14
    pushq %r15
    subq $64, %rsp

    movq %rdi, %rax                     // %rax = base address

    // 对 4 组对角线分别使用对角线缩减
    mix_diag_grp %rax, 0, 80, 160, 240
    mix_diag_grp %rax, 16, 96, 176, 192
    mix_diag_grp %rax, 32, 112, 128, 208
    mix_diag_grp %rax, 48, 64, 144, 224

    addq $64, %rsp
    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %rbp
    popq %rbx
    ret
.size mix_diagonal_4x4_st, .-mix_diagonal_4x4_st

