    movq %r13, %rsi
    call add_constant_4x4_st

    // 4. mix diagonal
    movq %r12, %rdi
    call mix_diagonal_4x4_st

    popq %r13
    popq %r12
    ret
.size permutation_p_4x4_st, .-permutation_p_4x4_st

