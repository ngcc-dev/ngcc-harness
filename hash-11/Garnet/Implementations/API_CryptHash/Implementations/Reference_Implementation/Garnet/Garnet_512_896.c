static const uint64_t reduction_table_1_MC4[2] = { 0x0, 0x87 };
static const uint64_t reduction_table_1_MD4[2] = { 0x0000000000000000, 0x0000000020008005 };

/* 辅助异或函数 */
static inline garnet_u128_t xor128(garnet_u128_t x, garnet_u128_t y) {
    garnet_u128_t z;
    z.v[0] = x.v[0] ^ y.v[0];
    z.v[1] = x.v[1] ^ y.v[1];
    return z;
}

static inline void zero128(garnet_u128_t* x) {
    x->v[0] = 0;
    x->v[1] = 0;
}

static garnet_u128_t gf128_mul_alpha_aa_MC4(garnet_u128_t a) {
    garnet_u128_t mask_low = { { 0x0, 0xFFFFFFFFFFFFFFFFULL } };
    garnet_u128_t result, carry, reducer;
    uint64_t tmp;

    result.v[1] = SHL64(a.v[1], 1);
    result.v[0] = SHL64(a.v[0], 1);

    carry.v[1] = SHR64(a.v[1], 63);
    carry.v[0] = SHR64(a.v[0], 63);
    tmp = carry.v[0];
    carry.v[0] = carry.v[1];
    carry.v[1] = tmp;

    carry.v[1] &= mask_low.v[1];
    carry.v[0] &= mask_low.v[0];

    result = xor128(result, carry);

    uint64_t bits = SHR64(a.v[1], 63);
    reducer.v[1] = 0;
    reducer.v[0] = reduction_table_1_MC4[bits & 1];

    return xor128(result, reducer);
}

static garnet_u128_t gf128_mul_alpha_aa_MD4(garnet_u128_t a) {
    garnet_u128_t mask_low = { { 0x0, 0xFFFFFFFFFFFFFFFFULL } };
    garnet_u128_t result, carry, reducer;
    uint64_t tmp;

    result.v[1] = SHL64(a.v[1], 1);
    result.v[0] = SHL64(a.v[0], 1);

    carry.v[1] = SHR64(a.v[1], 63);
    carry.v[0] = SHR64(a.v[0], 63);
    tmp = carry.v[0];
    carry.v[0] = carry.v[1];
    carry.v[1] = tmp;

    carry.v[1] &= mask_low.v[1];
    carry.v[0] &= mask_low.v[0];

    result = xor128(result, carry);

    uint64_t bits = SHR64(a.v[1], 63);
    reducer.v[1] = 0;
    reducer.v[0] = reduction_table_1_MD4[bits & 1];

    return xor128(result, reducer);
}

static void mix_column_4x4(garnet_u128_t state[STATE_4x4]) {
    int col, ind0, ind1, ind2, ind3;
    garnet_u128_t t0, t1, t2, t3;

    for (col = 0; col < 4; col++) {
        ind0 = col; ind1 = col + 4; ind2 = col + 8; ind3 = col + 12;

        zero128(&t0);
        t0 = xor128(t0, gf128_mul_alpha_aa_MC4(state[ind0]));
        t0 = xor128(t0, xor128(gf128_mul_alpha_aa_MC4(state[ind1]), state[ind1]));
        t0 = xor128(t0, state[ind2]);
        t0 = xor128(t0, state[ind3]);

        zero128(&t1);
        t1 = xor128(t1, state[ind0]);
        t1 = xor128(t1, gf128_mul_alpha_aa_MC4(state[ind1]));
        t1 = xor128(t1, xor128(gf128_mul_alpha_aa_MC4(state[ind2]), state[ind2]));
        t1 = xor128(t1, state[ind3]);

        zero128(&t2);
        t2 = xor128(t2, state[ind0]);
        t2 = xor128(t2, state[ind1]);
        t2 = xor128(t2, gf128_mul_alpha_aa_MC4(state[ind2]));
        t2 = xor128(t2, xor128(gf128_mul_alpha_aa_MC4(state[ind3]), state[ind3]));

        zero128(&t3);
        t3 = xor128(t3, xor128(gf128_mul_alpha_aa_MC4(state[ind0]), state[ind0]));
        t3 = xor128(t3, state[ind1]);
        t3 = xor128(t3, state[ind2]);
        t3 = xor128(t3, gf128_mul_alpha_aa_MC4(state[ind3]));

        state[ind0] = t0; state[ind1] = t1; state[ind2] = t2; state[ind3] = t3;
    }
}

