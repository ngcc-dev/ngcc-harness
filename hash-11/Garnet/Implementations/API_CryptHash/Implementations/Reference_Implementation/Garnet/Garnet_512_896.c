/* 安全提取代换表成员的 inline 函数 */
static inline uint32_t get_te(const uint8_t* table, uint8_t index) {
    uint32_t val;
    memcpy(&val, table + (size_t)index * 4, 4);
    return val;
}

/* 寄存器级优化的完全标准兼容 aesround 函数 */
static inline void aesround(uint8_t* out, const uint8_t* in, const uint8_t* rk) {
    uint32_t rk32[4];
    uint32_t out32[4];
    memcpy(rk32, rk, 16);

    out32[0] = get_te(TE0, in[0]) ^ get_te(TE1, in[5]) ^ get_te(TE2, in[10]) ^ get_te(TE3, in[15]) ^ rk32[0];
    out32[1] = get_te(TE0, in[4]) ^ get_te(TE1, in[9]) ^ get_te(TE2, in[14]) ^ get_te(TE3, in[3])  ^ rk32[1];
    out32[2] = get_te(TE0, in[8]) ^ get_te(TE1, in[13]) ^ get_te(TE2, in[2])  ^ get_te(TE3, in[7])  ^ rk32[2];
    out32[3] = get_te(TE0, in[12])^ get_te(TE1, in[1])  ^ get_te(TE2, in[6])  ^ get_te(TE3, in[11]) ^ rk32[3];

    memcpy(out, out32, 16);
}

