static struct garnet_u128_t xor128(struct  garnet_u128_t x, struct  garnet_u128_t y)
{
    struct garnet_u128_t z = { 0,0 };

    z.v[1] = x.v[1] ^ y.v[1];
    z.v[0] = x.v[0] ^ y.v[0];

    return z;
}

static void zero128(struct  garnet_u128_t* x)
{
    x->v[1] = 0;
    x->v[0] = 0;
}

static void mix_column_4x4_st(struct  garnet_u128_t state[STATE_4x4])//对应于4阶矩阵的x^128+x^7+x^2+x+1
{
    int col, ind0, ind1, ind2, ind3;
    struct  garnet_u128_t t0, t1, t2, t3;

    zero128(&t0);
    zero128(&t1); 
    zero128(&t2); 
    zero128(&t3); 

    for (int col = 0; col < 4; col++)
    {
        t0.v[1] = 0; t0.v[0] = 0;
        ind0 = col;
        ind1 = col + 4;
        ind2 = col + 8;
        ind3 = col + 12;

        t0 = xor128(t0, gf128_mul_alpha_aa_MC4_st(state[ind0]));
        t0 = xor128(t0, xor128(gf128_mul_alpha_aa_MC4_st(state[ind1]), state[ind1]));
        t0 = xor128(t0, state[ind2]);
        t0 = xor128(t0, state[ind3]);

        zero128(&t1);
        t1 = xor128(t1, state[ind0]);
        t1 = xor128(t1, gf128_mul_alpha_aa_MC4_st(state[ind1]));
        t1 = xor128(t1, xor128(gf128_mul_alpha_aa_MC4_st(state[ind2]), state[ind2]));
        t1 = xor128(t1, state[ind3]);

        zero128(&t2);
        t2 = xor128(t2, state[ind0]);
        t2 = xor128(t2, state[ind1]);
        t2 = xor128(t2, gf128_mul_alpha_aa_MC4_st(state[ind2]));
        t2 = xor128(t2, xor128(gf128_mul_alpha_aa_MC4_st(state[ind3]), state[ind3]));

        zero128(&t3);
        t3 = xor128(t3, xor128(gf128_mul_alpha_aa_MC4_st(state[ind0]), state[ind0]));
        t3 = xor128(t3, state[ind1]);
        t3 = xor128(t3, state[ind2]);
        t3 = xor128(t3, gf128_mul_alpha_aa_MC4_st(state[ind3]));

        state[ind0] = t0;
        state[ind1] = t1;
        state[ind2] = t2;
        state[ind3] = t3;
    }
}


