static struct garnet_u128_t gf128_mul_alpha_aa_MC4_st(struct  garnet_u128_t a)
{
    struct  garnet_u128_t mask_low = { 0x0, 0xFFFFFFFFFFFFFFFF };//高64位全为1
    struct  garnet_u128_t result = {0,0}, reducer = { 0,0 }, carry = { 0,0 };
    u64 tmp = 0, msb[2] = { 0,0 }, bits = 0;

    // 左移1位
    result.v[1] = 0; result.v[0] = 0;
    result.v[1] = SHL64(a.v[1], 1);
    result.v[0] = SHL64(a.v[0], 1);


    carry.v[1] = SHR64(a.v[1], 63);
    carry.v[0] = SHR64(a.v[0], 63);
    tmp = carry.v[0];
    carry.v[0] = carry.v[1];
    carry.v[1] = tmp;

    carry.v[1] &= mask_low.v[1];
    carry.v[0] &= mask_low.v[0];

    result.v[1] ^= carry.v[1];
    result.v[0] ^= carry.v[0];

    
    msb[1] = SHR64(a.v[1], 63);
    msb[0] = SHR64(a.v[0], 63);
    bits = msb[1];

    reducer.v[1] = 0;
    reducer.v[0] = reduction_table_1_MC4[bits & 0x1];

    result.v[1] ^= reducer.v[1];
    result.v[0] ^= reducer.v[0];

    return result;
}


