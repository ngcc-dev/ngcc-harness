#ifndef HARE_PARAMETERS_H
#define HARE_PARAMETERS_H

#include <stdint.h>

#define CEIL_DIVIDE(a,b) (((a)/(b)) + (((a)%(b))?1:0))
#define MAX2(a,b) ((a)>(b)?(a):(b))
#define BITMASK(a,size) ((1ULL << ((a) % (size))) - 1ULL)

#define PARAM_SECURITY_BYTES 64
#define SEED_BYTES 64
#define SALT_BYTES 64
#define SHARED_SECRET_BYTES 64

#define PARAM_N 173981
#define PARAM_K 64
#define PARAM_OMEGA 259
#define PARAM_OMEGA_R 259
#define PARAM_OMEGA_E 449
#define PARAM_N1 151
#define PARAM_N2 1152
#define PARAM_N1N2 173952
#define PARAM_ALPHA 13

#define PARAM_COMP_N 51
#define PARAM_COMP_K 41
#define PARAM_COMP_R 2

#define PARAM_L1 (PARAM_N1 * PARAM_N2)
#define PARAM_COMP_Q (PARAM_L1 / PARAM_COMP_N)
#define PARAM_L2 (PARAM_COMP_Q * PARAM_COMP_N)
#define PARAM_NM (PARAM_COMP_K * PARAM_COMP_Q)
#define PARAM_NV2 (PARAM_L1 - PARAM_L2)
#define PARAM_NM_BITS PARAM_NM
#define PARAM_V2_BITS PARAM_NV2

#define VEC_N_SIZE_BYTES CEIL_DIVIDE(PARAM_N,8)
#define VEC_K_SIZE_BYTES PARAM_K
#define VEC_N1_SIZE_BYTES PARAM_N1
#define VEC_N1N2_SIZE_BYTES CEIL_DIVIDE(PARAM_N1N2,8)
#define VEC_NM_SIZE_BYTES CEIL_DIVIDE(PARAM_NM,8)
#define VEC_NV2_SIZE_BYTES CEIL_DIVIDE(PARAM_NV2,8)

#define VEC_N_SIZE_64 CEIL_DIVIDE(PARAM_N,64)
#define VEC_N1_SIZE_64 CEIL_DIVIDE(PARAM_N1,8)
#define VEC_N1N2_SIZE_64 CEIL_DIVIDE(PARAM_N1N2,64)
#define VEC_NM_SIZE_64 CEIL_DIVIDE(PARAM_NM,64)
#define VEC_NV2_SIZE_64 CEIL_DIVIDE(PARAM_NV2,64)
#define VEC_COMPRESSED_PAYLOAD_BITS (PARAM_NM + PARAM_NV2)
#define VEC_COMPRESSED_PAYLOAD_BYTES CEIL_DIVIDE(VEC_COMPRESSED_PAYLOAD_BITS,8)

#define PARAM_N_MU (4294967296ULL / PARAM_N)
#define UTILS_REJECTION_THRESHOLD ((16777216 / PARAM_N) * PARAM_N)
#define PARAM_OMEGA_MAX MAX2(MAX2(PARAM_OMEGA, PARAM_OMEGA_R), PARAM_OMEGA_E)

#define PARAM_M 8
#define PARAM_GF_POLY 0x11D
#define PARAM_GF_MUL_ORDER 255
#define PARAM_DELTA ((PARAM_N1 - PARAM_K) / 2)
#define PARAM_FFT 6

#define PUBLIC_KEY_BYTES 21812
#define SECRET_KEY_BYTES 22004
#define CIPHERTEXT_BYTES 39294

#endif
