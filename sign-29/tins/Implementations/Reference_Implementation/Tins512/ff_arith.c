void fe_add(fe a, fe b, fe c)
{
    for (int i = 0; i < EXT_DEGREE; i++)
    {
        c[i] = a[i] ^ b[i];
    }
}

void fe_or(fe a, fe b, fe c)
{
    for (int i = 0; i < EXT_DEGREE; i++)
    {
        c[i] = a[i] | b[i];
    }
}

void fe_mul(fe a, fe b, fe c)
{
    fe tmp, tmpb, tmpc;

    for (int j = 0; j < EXT_DEGREE; j++)
    {
        tmp[j] = a[j];
        tmpb[j] = b[j];
        tmpc[j] = 0;
    }


    for (int i = EXT_DEGREE - 1; i >= 0; i--)
    {
        fe t;

        for (int j = 0; j < EXT_DEGREE; j++)
        {
            ff12b_mul(tmpb[i], tmp[j], &t[j]);
        }

        fe_add(tmpc, t, tmpc);

        ff12b LeadCoeff = tmp[0];

        for (int j = 0; j < EXT_DEGREE - 1; j++)
        {
            tmp[j] = tmp[j + 1];
        }

        ff12b w;
        ff12b_mul(LeadCoeff, a84, &w);
        tmp[EXT_DEGREE - 1 - 84] ^= w;

        ff12b_mul(LeadCoeff, a0, &tmp[EXT_DEGREE - 1]);
    }

    for (int j = 0; j < EXT_DEGREE; j++)
    {
        c[j] = tmpc[j];
    }
}

int deg(fe a)
{
    int i;
    for (i = 0; i < EXT_DEGREE; i++)
    {
        if (a[i] != 0)
        {
            break;
        }
    }
    return EXT_DEGREE - 1 - i;
}

// compute r=a%b, with quotient q.  a = bq + r, where b!=0;
void rem(fe a, fe b, fe q, fe r)
{
    int i, j;

    int da = deg(a), db = deg(b);

    for (i = 0; i < EXT_DEGREE; i++)
    {
        r[i] = a[i];
        q[i] = 0;
    }

    if (da < db)
    {
        return;
    }

    fe NormalizedB, tmp;
    int dq = da - db;

    ff12b LeadCoeffB = b[EXT_DEGREE - 1 - db];

    ff12b Linv = z_inv[LeadCoeffB];
    for (i = 0; i < EXT_DEGREE; i++)
    {
        ff12b_mul(Linv, b[i], &NormalizedB[i]);
    }

    while (da >= db)
    {
        ff12b LeadCoeffR = r[EXT_DEGREE - 1 - da];
        q[EXT_DEGREE - 1 - (da - db)] = LeadCoeffR;
        for (j = 0; j < EXT_DEGREE; j++)
        {
            tmp[j] = 0;
        }
        for (j = 0; j <= db; j++)
        {
            ff12b_mul(LeadCoeffR, NormalizedB[EXT_DEGREE - 1 - j], &tmp[EXT_DEGREE - 1 - (da - db) - j]);
        }

        fe_add(r, tmp, r);

        da = deg(r);
    }

    for (i = 0; i < EXT_DEGREE; i++)
    {
        ff12b_mul(Linv, q[i], &q[i]);
    }
}

void f_div(fe a, fe b, fe q, fe r)
{
    int i, j;

    int da = EXT_DEGREE, db = deg(b);

    for (i = 0; i < EXT_DEGREE; i++)
    {
        r[i] = a[i];
        q[i] = 0;
    }

    fe NormalizedB, tmp;
    int dq = da - db;
    ff12b LeadCoeffB = b[EXT_DEGREE - 1 - db];
    ff12b Linv = z_inv[LeadCoeffB];
    for (i = 0; i < EXT_DEGREE; i++)
    {
        ff12b_mul(Linv, b[i], &NormalizedB[i]);
    }

    // Deal with X^22+...
    q[EXT_DEGREE - 1 - (da - db)] = 1;
    for (j = 0; j < EXT_DEGREE; j++)
    {
        tmp[j] = 0;
    }
    for (j = 0; j < db; j++)
    {
        tmp[EXT_DEGREE - 1 - j - (da - db)] = NormalizedB[EXT_DEGREE - 1 - j];
    }

    fe_add(r, tmp, r);
    da = deg(r);

    while (da >= db)
    {
        ff12b LeadCoeffR = r[EXT_DEGREE - 1 - da];
        q[EXT_DEGREE - 1 - (da - db)] = LeadCoeffR;
        for (j = 0; j < EXT_DEGREE; j++)
        {
            tmp[j] = 0;
        }
        for (j = 0; j <= db; j++)
        {
            ff12b_mul(LeadCoeffR, NormalizedB[EXT_DEGREE - 1 - j], &tmp[EXT_DEGREE - 1 - (da - db) - j]);
        }

        fe_add(r, tmp, r);

        da = deg(r);
    }

    for (i = 0; i < EXT_DEGREE; i++)
    {
        ff12b_mul(Linv, q[i], &q[i]);
    }
}

void fe_inv(fe a, fe a_inv)
{
    int df = EXT_DEGREE, da = deg(a), dq = df - da;

    int i, j;
    if (da == 0)
    {
        for (i = 0; i < EXT_DEGREE; i++)
        {
            a_inv[i] = 0;
        }
        a_inv[EXT_DEGREE - 1] = z_inv[a[EXT_DEGREE - 1]];
        return;
    }

    fe f, x_0, x_1, x, y_0, y_1, y;
    fe r;
    fe q;
    fe w, ta;

    for (i = 0; i < EXT_DEGREE; i++)
    {
        x_0[i] = 0;
        x_1[i] = 0;
        y_0[i] = 0;
        y_1[i] = 0;
        x[i] = 0;
        f[i] = 0;
        a_inv[i] = 0;
        y[i] = 0;
        q[i] = 0;
        r[i] = 0;
        ta[i] = a[i];
        w[i] = 0;
    }

    f[EXT_DEGREE - 1 - 84] = a84;
    f[EXT_DEGREE - 1 - 0] = a0;

    x_0[EXT_DEGREE - 1] = 1;

    y_1[EXT_DEGREE - 1] = 1;

    f_div(f, a, q, r);

    while (deg(r) != 0)
    {
        fe tmp;

        fe_mul(q, x_1, tmp);
        fe_add(x_0, tmp, x);
        fe_mul(q, y_1, tmp);
        fe_add(y_0, tmp, y);

        for (i = 0; i < EXT_DEGREE; i++)
        {
            x_0[i] = x_1[i];
            x_1[i] = x[i];

            y_0[i] = y_1[i];
            y_1[i] = y[i];

            f[i] = a[i];
            a[i] = r[i];
            q[i] = 0;
        }

        rem(f, a, q, r);
    }

    fe_mul(q, x_1, w);
    fe_add(x_0, w, x);

    fe_mul(q, y_1, w);
    fe_add(y_0, w, y);

    ff12b r_inv = z_inv[r[EXT_DEGREE - 1]];

    for (i = 0; i < EXT_DEGREE; i++)
    {
        ff12b_mul(y[i], r_inv, &a_inv[i]);
        a[i] = ta[i];
    }
}

void fe_ff12b_mul(fe a, ff12b b, fe c)
{
    fe tmp;

    for (int i = 0; i < EXT_DEGREE; i++)
    {
        ff12b_mul(a[i], b, &(tmp[i]));
        c[i] = tmp[i];
    }
}

void fe_inner(fe a[], fe b[], int dim, fe product)
{
    fe tmp, tp;
    for (int i = 0; i < EXT_DEGREE; i++)
    {
        tmp[i] = 0;
        tp[i] = 0;
    }

    for (int j = 0; j < dim; j++)
    {
        fe_mul(a[j], b[j], tmp);
        fe_add(tp, tmp, tp);
    }
    for (int i = 0; i < EXT_DEGREE; i++)
    {
        product[i] = tp[i];
    }
}

// product = <a,,b> where a\in fe^{dim}, b\in ff12b^{dim}
void fe_ff12b_inner(fe a[], ff12b b[], int dim, fe product)
{
    fe tmp, tp;
    for (int i = 0; i < EXT_DEGREE; i++)
    {
        tmp[i] = 0;
        tp[i] = 0;
    }
    for (int i = 0; i < dim; i++)
    {
        fe_ff12b_mul(a[i], b[i], tmp);
        fe_add(tp, tmp, tp);
    }
    for (int i = 0; i < EXT_DEGREE; i++)
    {
        product[i] = tp[i];
    }
}

// product = <a,,b> where a\in fe^{dim}, b\in f2^{dim}
void fe_f2_inner(fe a[], unsigned char b[], int dim, fe product)
{
    fe tp;
    for (int i = 0; i < EXT_DEGREE; i++)
    {
        tp[i] = 0;
    }
    for (int i = 0; i < dim; i++)
    {
        if ((b[i / 8] >> (7 - (i & 7))) & 1)
        {
            fe_add(tp, a[i], tp);
        }
    }
    for (int i = 0; i < EXT_DEGREE; i++)
    {
        product[i] = tp[i];
    }
}

// compress array v[] into nonce[], where sizeof(nonce) = dim * FE_BYTES
