/* Function: axis_zero32_expr_word_extract64. Extracts a 64-bit window from the generated zero-cycle word representation. */

static inline uint64_t axis_zero32_expr_word_extract64(const uint64_t reg[3], unsigned start) {
    const unsigned word = start >> 6;
    const unsigned shift = start & 63U;
    if (shift == 0U) {
        return reg[word];
    }
    return (reg[word] >> shift) | (reg[(word + 1U) % 3U] << (64U - shift));
}
/* Function: axis_zero32_expr_word_sbox6. Evaluates the generated word-parallel six-input SBox expression. */

static inline uint64_t axis_zero32_expr_word_sbox6(uint64_t x0, uint64_t x1, uint64_t x2, uint64_t x3, uint64_t x4, uint64_t x5) {
    return (x0 & x1) ^ (x2 & x3) ^ (x4 & x5);
}
